import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { selectProject } from './project_selection.mjs'

const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'dark' })
  page.setDefaultTimeout(10000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode: 'dark', language: 'en' })))
  await page.goto(process.argv[2] + '/projects/admin/?search_type=sthpw/project&view=table')
  await page.getByLabel('Login', { exact: true }).fill(process.env.STREAM_CHECK_LOGIN || 'admin')
  await page.getByLabel('Password', { exact: true }).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  const ready = () => page.waitForFunction(() => document.querySelector('.workspace-results')?.getAttribute('aria-busy') === 'false')
  await ready()
  await selectProject(page, process.env.STREAM_CHECK_PROJECT)
  await page.locator('.navigation-toggle').click()
  await page.locator('.type-list button[data-search-type="cg/scenes"]').first().click()
  await ready()
  await page.screenshot({ path: '../.screenshots/handler-current/stream-initial.png', animations: 'disabled' })
  await page.getByLabel('Change search results view', { exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'Continuous tree', exact: true }).click()
  await page.locator('.result-presentation:visible .result-item').first().waitFor()
  const notice = page.getByLabel('Dismiss notification', { exact: true })
  if (await notice.isVisible()) await notice.click()

  for (const [selector, height] of [['.topbar', 44], ['.search-header', 48], ['.workspace-tabs[data-kind="search"]', 48], ['.workspace-footer', 58]]) {
    assert.equal((await page.locator(selector).boundingBox()).height, height, selector)
  }
  assert.equal((await page.locator('.workspace-rail').boundingBox()).width, 48)
  assert.equal((await page.locator('.workspace-browser').boundingBox()).y, 48)
  assert.equal(await page.locator('.workspace-tab-menu').isVisible(), false, 'One fitted tab has no permanent overflow button')
  await page.screenshot({ path: '../.screenshots/handler-current/stream-main.png', animations: 'disabled' })
  const before = await page.locator('.workspace-main').boundingBox()
  await page.locator('.navigation-toggle').click()
  await page.locator('.sidebar').waitFor()
  assert.deepEqual(await page.locator('.workspace-main').boundingBox(), before, 'Navigation overlays the workspace')
  assert.equal((await page.locator('.sidebar').boundingBox()).width, 360)
  await page.screenshot({ path: '../.screenshots/handler-current/stream-navigation.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  await page.locator('.settings-menu > summary').click()
  await page.locator('.settings-menu').getByRole('button', { name: 'Current view to All Tabs', exact: true }).waitFor()
  assert.deepEqual(await page.locator('.settings-menu > .account-panel').evaluate(node => {
    const style = getComputedStyle(node)
    return [style.transitionProperty, style.transitionDuration]
  }), ['scale, opacity', '0.072s, 0.048s'])
  await page.screenshot({ path: '../.screenshots/handler-current/stream-menu.png', animations: 'disabled' })
  await page.keyboard.press('ArrowDown')
  assert.equal(await page.locator('.settings-menu .account-panel button').first().evaluate(node => node === document.activeElement), true)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.settings-menu > summary').evaluate(node => node === document.activeElement), true)
  const trigger = await page.locator('.settings-menu > summary').boundingBox()
  await page.mouse.move(trigger.x + trigger.width / 2, trigger.y + trigger.height / 2)
  await page.mouse.down()
  const pulse = page.locator('.settings-menu > summary > .control-ripple-clip > .control-ripple')
  assert.equal(await pulse.getAttribute('aria-hidden'), 'true')
  assert.equal(Math.round((await pulse.evaluate(node => parseFloat(node.style.width))) * 10), Math.round(trigger.width * 2.2 * 10))
  await page.mouse.up()
  await page.keyboard.press('Escape')
  await page.locator('.project-picker').click()
  await page.screenshot({ path: '../.screenshots/handler-current/stream-project-chooser.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  await page.getByLabel('Add new search tab', { exact: true }).click()
  await ready()
  await page.getByLabel('Change search results view', { exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'Compact rows', exact: true }).click()
  await page.locator('.result-presentation:visible .result-item').first().waitFor()
  await page.getByLabel('More options', { exact: true }).click()
  await page.getByRole('button', { name: 'Current view to All Tabs', exact: true }).click()
  await page.locator('.workspace-tabs[data-kind="search"] [role="tab"]').first().click()
  await page.locator('.result-presentation:visible .result-item').first().waitFor()
  await page.getByLabel('More options', { exact: true }).click()
  await page.locator('.settings-menu').getByRole('button', { name: 'Save Preferences', exact: true }).click()
  const saved = await page.evaluate(project => JSON.parse(localStorage.getItem('tactic_stream.workspace.admin'))[project], process.env.STREAM_CHECK_PROJECT)
  assert(saved.sections.flatMap(section => section.tabs).every(tab => tab.state.resultMode === 'compact'), 'The current view is applied to all open tabs in the project')

  for (const width of [720, 360, 320]) {
    await page.setViewportSize({ width, height: 740 })
    await page.waitForFunction(() => document.querySelector('.workspace-tabs[data-kind="search"]')?.classList.contains('compact'))
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    const results = await page.locator('.workspace-results').boundingBox()
    assert(results.height > 500, 'The result viewport remains the main scroll area')
    await page.getByLabel('Result actions', { exact: true }).click()
    await page.getByLabel('Group items', { exact: true }).click()
    const group = page.getByRole('menuitemradio', { name: 'SObject status', exact: true })
    const box = await group.boundingBox()
    assert(box.x >= 0 && box.x + box.width <= width)
    await group.click()
    await page.keyboard.press('Escape')
    if (await notice.isVisible()) await notice.click()
    await page.screenshot({ path: `../.screenshots/handler-current/stream-main-${width}.png`, animations: 'disabled' })
  }
  assert.deepEqual(errors, [])
  console.log('PASS: native main-window dimensions, overlay navigation, menu keyboard, project chooser, view propagation and compact result actions')
} finally { await browser.close() }
