import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { selectProject } from './project_selection.mjs'

const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'dark', hasTouch: true })
  page.setDefaultTimeout(12000)
  const errors = [], queries = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    if (request.url().endsWith('/admin/rpc')) {
      const payload = request.postDataJSON()
      if (payload.method === 'query') queries.push(payload.args)
    }
  })
  await page.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode: 'dark', language: 'en' })))
  await page.goto(process.argv[2] + '/projects/admin/?search_type=sthpw/project&view=table')
  await page.getByLabel('Login', { exact: true }).fill(process.env.STREAM_CHECK_LOGIN || 'admin')
  await page.getByLabel('Password', { exact: true }).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.locator('.project-picker').waitFor()
  await selectProject(page, process.env.STREAM_CHECK_PROJECT)
  await page.waitForFunction(() => document.querySelector('.workspace-results')?.getAttribute('aria-busy') === 'false')
  const url = page.url(), selected = await page.locator('.project-picker').getAttribute('data-project')
  const shortcuts = page.locator('.workspace-shortcuts')
  assert.deepEqual(await shortcuts.locator('.system-activity-trigger, :scope > button').evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label'))), ['System activity', 'Commit Queue', 'Activity Feed'])
  assert.equal(await page.getByRole('button', { name: 'Change history', exact: true }).count(), 0)
  assert.equal(await page.getByRole('button', { name: 'Background queue', exact: true }).count(), 0)
  await page.screenshot({ path: '../.screenshots/handler-current/stream-main-shortcuts.png', animations: 'disabled' })

  await shortcuts.getByRole('button', { name: 'Commit Queue', exact: true }).click()
  const queue = page.locator('.commit-queue:visible')
  await queue.getByText('No file check-ins yet.', { exact: true }).waitFor()
  assert.equal(await queue.getByText('Tactic Dispatcher', { exact: true }).count(), 0)
  await page.getByLabel('Close panel: Commit Queue', { exact: true }).click()
  await shortcuts.getByRole('button', { name: 'Activity Feed', exact: true }).click()
  const feed = page.getByRole('dialog', { name: 'Activity Feed', exact: true })
  await feed.getByLabel('Search activity', { exact: true }).waitFor()
  await feed.getByLabel('Close Activity Feed', { exact: true }).click()
  assert.equal(page.url(), url)
  assert.equal(await page.locator('.project-picker').getAttribute('data-project'), selected)
  assert(!queries.some(args => JSON.stringify(args).includes('sthpw/queue') || JSON.stringify(args).includes('sthpw/transaction_log')), 'Shortcuts must not query a replacement table')

  await page.getByLabel('More options', { exact: true }).click()
  await page.locator('.settings-menu').getByRole('button', { name: 'Save Preferences', exact: true }).click()
  await page.keyboard.press('Escape')
  let pingError = 'Unable to reach the server.'
  await page.route('**/admin/rpc', async route => {
    if (route.request().postDataJSON().method === 'ping') return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: pingError }) })
    return route.continue()
  })
  await page.getByLabel('Connection', { exact: true }).click()
  await page.getByRole('button', { name: 'Ping now', exact: true }).click()
  await page.locator('.notification-card[role="alert"]').filter({ hasText: 'Unable to reach the server.' }).waitFor()
  await page.keyboard.press('Escape')
  await shortcuts.getByRole('button', { name: 'System activity', exact: true }).click()
  const history = page.getByRole('dialog', { name: 'Notifications', exact: true })
  await history.locator('.system-activity-history').getByText('Preferences saved', { exact: true }).waitFor()
  await history.locator('.system-activity-history').getByText('Unable to reach the server.', { exact: true }).waitFor()
  assert.equal(await history.locator('.system-activity-event').count(), 2)
  await page.screenshot({ path: '../.screenshots/handler-current/stream-system-activity.png', animations: 'disabled' })
  await history.getByRole('radio', { name: 'Server', exact: true }).click()
  assert.equal(await history.locator('.system-activity-event').count(), 1)
  await history.getByRole('radio', { name: 'Client', exact: true }).click()
  await history.locator('.system-activity-history').getByText('Preferences saved', { exact: true }).waitFor()
  assert.equal(await history.locator('.system-activity-event').count(), 1)
  await history.getByRole('radio', { name: 'Check-in', exact: true }).click()
  await history.locator('.system-activity-history').getByText('No events in this group', { exact: true }).waitFor()
  await history.getByLabel('Maximize window', { exact: true }).click()
  assert.equal(Math.round((await history.boundingBox()).width), 1440)
  await history.getByLabel('Restore window', { exact: true }).click()
  await history.getByLabel('Close Notifications', { exact: true }).click()

  for (const width of [360, 320]) {
    await page.setViewportSize({ width, height: 740 })
    await page.getByLabel('More options', { exact: true }).tap()
    await page.locator('.settings-menu').getByRole('button', { name: 'System activity', exact: true }).tap()
    await history.getByRole('radio', { name: 'All', exact: true }).tap()
    assert.equal(await history.getByRole('radio', { name: 'Server', exact: true }).locator('.app-icon').isVisible(), true)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    assert.equal(await history.evaluate(node => node.scrollWidth <= node.clientWidth), true)
    await page.screenshot({ path: `../.screenshots/handler-current/stream-system-activity-${width}.png`, animations: 'disabled' })
    if (width === 360) await history.getByLabel('Clear history', { exact: true }).tap()
    else assert.equal(await history.getByLabel('Clear history', { exact: true }).isDisabled(), true)
    await history.locator('.system-activity-history').getByText('No events in this group', { exact: true }).waitFor()
    await history.getByLabel('Close Notifications', { exact: true }).tap()
    await page.getByLabel('More options', { exact: true }).tap()
    await page.locator('.settings-menu').getByRole('button', { name: 'Commit Queue', exact: true }).tap()
    await queue.getByText('No file check-ins yet.', { exact: true }).waitFor()
    await page.getByLabel('Close panel: Commit Queue', { exact: true }).tap()
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  pingError = 'Unable to reach the server. Second attempt.'
  await page.getByLabel('Connection', { exact: true }).click()
  await Promise.all([page.waitForResponse(response => response.url().endsWith('/admin/rpc') && response.request().postDataJSON().method === 'ping'),
    page.getByRole('button', { name: 'Ping now', exact: true }).click()])
  await page.keyboard.press('Escape')
  await shortcuts.getByRole('button', { name: 'System activity', exact: true }).click()
  await history.locator('.system-activity-history').getByText(pingError, { exact: true }).waitFor()
  await history.getByLabel('Close Notifications', { exact: true }).click()
  await page.unroute('**/admin/rpc')
  await page.getByLabel('Account', { exact: true }).click()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.getByLabel('Login', { exact: true }).fill(process.env.STREAM_CHECK_LOGIN || 'admin')
  await page.getByLabel('Password', { exact: true }).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await shortcuts.getByRole('button', { name: 'System activity', exact: true }).click()
  await history.waitFor()
  assert.equal(await history.locator('.system-activity-history').getByText(pingError, { exact: true }).count(), 0, 'The previous session history must be cleared; new login operations may appear')
  await history.getByLabel('Close Notifications', { exact: true }).click()
  assert.deepEqual(errors, [])
  console.log('PASS: native shortcut order and distinct screens, unchanged workspace, session history filters/clear/logout, common maximize and touch at 360/320')
} finally { await browser.close() }
