async function swipe(locator, direction) {
  await page.waitForFunction(() => document.querySelector('.result-presentation:has(.mobile-results)')?.getAttribute('aria-busy') === 'false')
  await page.waitForFunction(() => !document.querySelector('.mobile-result-forward-enter-active,.mobile-result-back-enter-active'))
  const box = await locator.locator('.result-item-copy').boundingBox()
  const session = await context.newCDPSession(page)
  const x = direction === 'left' ? box.x + box.width * .6 : box.x + box.width * .4
  const y = box.y + box.height / 2
  await session.send('Input.dispatchTouchEvent', { type:'touchStart', touchPoints:[{ x,y }] })
  for (let i=1; i<=8; i++) await session.send('Input.dispatchTouchEvent', { type:'touchMove', touchPoints:[{ x:x + (direction === 'left' ? -1 : 1) * i * 14,y }] })
  await session.send('Input.dispatchTouchEvent', { type:'touchEnd', touchPoints:[] })
  await session.detach()
}
