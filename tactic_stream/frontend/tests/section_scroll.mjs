import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { selectProject } from './project_selection.mjs'

const base = process.argv[2], project = process.env.STREAM_CHECK_PROJECT
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1000, height: 740 }, hasTouch: true, colorScheme: 'dark' })
  page.setDefaultTimeout(12000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode: 'dark', language: 'en' })))
  await page.goto(base + '/projects/admin/?search_type=sthpw/project&view=table')
  await page.getByLabel('Login', { exact: true }).fill(process.env.STREAM_CHECK_LOGIN || 'admin')
  await page.getByLabel('Password', { exact: true }).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await selectProject(page, project)
  const session = await page.evaluate(() => JSON.parse(localStorage.getItem('tactic_stream.session') || sessionStorage.getItem('tactic_stream.session')))
  const response = await page.request.post(base + '/admin/rpc', { data: { method: 'query', args: [{ ticket: session.ticket, project }, 'sthpw/search_object'] } })
  assert.equal(response.status(), 200)
  const registry = (await response.json()).result
  const names = ['cg/assets', 'cg/textures', 'cg/scenes', 'cg/shot', 'sthpw/task', 'sthpw/note', 'sthpw/login', 'sthpw/login_group', 'sthpw/snapshot', 'sthpw/file', 'sthpw/project', 'sthpw/search_object', 'sthpw/pipeline', 'sthpw/status', 'sthpw/connection', 'sthpw/message', 'sthpw/transaction_log', 'sthpw/exception_log', 'sthpw/debug_log', 'sthpw/custom_script', 'sthpw/db_resource', 'sthpw/trigger']
  const available = names.filter(name => registry.some(row => row.search_type === name))
  assert(available.length >= 20)
  const ready = () => page.waitForFunction(() => document.querySelector('.workspace-results')?.getAttribute('aria-busy') === 'false')
  for (const type of available) {
    await page.goto(base + '/projects/' + encodeURIComponent(project) + '/?' + new URLSearchParams({ search_type: type, view: 'table' }))
    await ready()
  }
  const rail = page.locator('.section-tab-rail'), rows = rail.locator('.section-tab-row'), popup = page.locator('.section-tab-reveal')
  assert(await rail.evaluate(node => node.scrollHeight > node.clientHeight))
  const main = page.locator('.workspace-main'), results = page.locator('.workspace-results')
  const mainBounds = await main.boundingBox(), resultsScroll = await results.evaluate(node => node.scrollTop)
  await rail.evaluate(node => node.scrollTop = 0)
  await rows.first().getByRole('tab').hover()
  await page.waitForFunction(() => document.querySelector('.section-tab-reveal')?.matches(':popover-open'))
  const firstTitle = await popup.getAttribute('aria-label')
  await page.waitForTimeout(80)
  await page.screenshot({ path: '../.screenshots/handler-current/stream-section-rail-long.png' })
  await page.mouse.wheel(0, 90)
  await page.waitForFunction(() => document.querySelector('.section-tab-rail').scrollTop >= 85)
  assert.equal(await results.evaluate(node => node.scrollTop), resultsScroll)
  assert.deepEqual(await main.boundingBox(), mainBounds)
  assert(!await popup.evaluate(node => node.matches(':popover-open')) || await popup.getAttribute('aria-label') !== firstTitle,
    'The old reveal is dismissed or replaced by the row now under the mouse')
  await rail.evaluate(node => node.scrollTop = 0)
  await rows.nth(3).getByRole('tab').hover()
  await page.waitForFunction(() => document.querySelector('.section-tab-reveal')?.matches(':popover-open'))
  await page.mouse.move(600, 600)
  await rail.evaluate(node => node.scrollTop = 45)
  await page.waitForTimeout(80)
  assert(Math.abs((await popup.boundingBox()).y - (await rows.nth(3).boundingBox()).y - 2) < 1, 'Reveal follows a visible scrolled row')
  // A transient reveal must not cover the separately opened navigation drawer.
  await page.locator('.navigation-toggle').click()
  await page.locator('.sidebar').waitFor()
  await page.waitForTimeout(80)
  assert.equal(await popup.evaluate(node => node.matches(':popover-open')), false, 'Navigation opening dismisses the rail reveal')
  await page.keyboard.press('Escape')
  await rows.first().getByRole('tab').hover()
  await page.waitForFunction(() => document.querySelector('.section-tab-reveal')?.matches(':popover-open'))
  await page.getByLabel('More options', { exact: true }).click()
  await page.locator('.settings-menu').getByRole('button', { name: 'Configuration', exact: true }).click()
  await page.getByRole('dialog', { name: 'Configuration', exact: true }).waitFor()
  assert.equal(await popup.evaluate(node => node.matches(':popover-open')), false, 'Configuration dismisses the transient reveal')
  await page.getByRole('dialog', { name: 'Configuration', exact: true }).getByRole('button', { name: 'Close', exact: true }).click()
  await rail.evaluate(node => node.scrollTop = 0)
  await rows.first().getByRole('tab').focus()
  await page.keyboard.press('End')
  assert.equal(await rows.last().getByRole('tab').evaluate(node => node === document.activeElement), true)
  assert(await rail.evaluate(node => node.scrollTop > 0), 'Keyboard focus reveals the last section inside the rail')
  assert.equal(await results.evaluate(node => node.scrollTop), resultsScroll)
  assert.deepEqual(await main.boundingBox(), mainBounds)
  await page.keyboard.press('Home')
  assert.equal(await rows.first().getByRole('tab').evaluate(node => node === document.activeElement), true)
  await rail.evaluate(node => node.scrollTop = 0)
  await rows.nth(10).getByRole('tab').hover()
  await page.waitForFunction(() => document.querySelector('.section-tab-reveal')?.matches(':popover-open'))
  await page.setViewportSize({ width: 1000, height: 300 })
  await page.waitForTimeout(80)
  assert.equal(await popup.evaluate(node => node.matches(':popover-open')), false, 'Resize dismisses a reveal whose row is outside the rail')
  for (const width of [360, 320]) {
    await page.setViewportSize({ width, height: 740 })
    await rail.evaluate(node => node.scrollTop = 0)
    await page.mouse.move(width - 30, 600)
    await page.keyboard.press('Escape')
    await page.waitForTimeout(400)
    const before = await rows.evaluateAll(nodes => nodes.map(node => node.dataset.sectionId))
    const selected = await rail.locator('[aria-selected="true"]').getAttribute('aria-label')
    const touch = await page.context().newCDPSession(page)
    await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 24, y: 380 }] })
    for (const y of [350, 310, 270, 230, 190]) {
      await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 24, y }] })
      await page.waitForTimeout(35)
    }
    await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await page.waitForTimeout(600)
    assert(await rail.evaluate(node => node.scrollTop > 100), 'Touch scroll moves the section rail')
    assert.equal(await rail.locator('.dragging').count(), 0)
    assert.equal(await popup.evaluate(node => node.matches(':popover-open')), false, 'Scrolling never triggers a long-press menu')
    assert.deepEqual(await rows.evaluateAll(nodes => nodes.map(node => node.dataset.sectionId)), before)
    assert.equal(await rail.locator('[aria-selected="true"]').getAttribute('aria-label'), selected)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.screenshot({ path: `../.screenshots/handler-current/stream-section-rail-scroll-${width}.png` })
    await touch.detach()
  }
  assert.deepEqual(errors, [])
  console.log('PASS long section rail: wheel/keyboard isolation, reveal alignment, resize/navigation dismissal and touch scroll at 360/320')
} finally { await browser.close() }
