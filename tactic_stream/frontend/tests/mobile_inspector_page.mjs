import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { selectProject } from './project_selection.mjs'

const browser = await chromium.launch({headless:true})
const page = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
page.setDefaultTimeout(12000)
const errors = []
page.on('pageerror',error => errors.push(error.message))
const project = process.env.STREAM_CHECK_PROJECT
const inspector = page.getByRole('region',{name:'Task Inspector',exact:true})
const dock = page.locator('[data-dock="notes"]')
const results = page.locator('.workspace-browser .mobile-results:visible')
async function openObjectNotes() {
  await results.locator('.mobile-result-header').getByRole('button',{name:'Notes',exact:true}).tap()
  const chooser = page.getByRole('dialog',{name:'Choose process',exact:true})
  await chooser.or(inspector).waitFor()
  if (await chooser.isVisible()) await chooser.getByRole('menuitem',{name:/publish/i}).tap()
  await inspector.getByLabel('Note text',{exact:true}).waitFor()
}
async function geometry() {
  const bar = await page.locator('.topbar').boundingBox(), body = await inspector.boundingBox()
  assert.ok(body.y >= bar.y+bar.height,'Inspector must stay below the main application header')
  const composer = await inspector.locator('.note-composer').boundingBox()
  const context = await inspector.locator('.inspector-context').boundingBox(), timeline = await inspector.locator('.notes-timeline').boundingBox()
  assert.ok(context.y+context.height <= timeline.y+1,'Object, process and Back stay above the timeline')
  assert.ok(context.height+composer.height <= 96,'Navigation and composer stay compact')
  assert.equal(await dock.locator('> .phone-panel-heading').count(),0,'Inspector does not duplicate a separate title below the application header')
  assert.ok(composer.y+composer.height <= page.viewportSize().height+1,'Composer stays inside the remaining viewport')
  assert.equal(await page.locator('dialog.notes-panel[open]').count(),0,'Inspector is a workspace page, not a modal covering the header')
  assert.equal(await page.getByRole('button',{name:'Open navigation',exact:true}).isEnabled(),true)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth),false)
}
try {
  await page.addInitScript(() => localStorage.setItem('tactic_stream.appearance',JSON.stringify({mode:'dark',language:'en'})))
  await page.goto(process.argv[2]+'/projects/'+project+'/?search_type=cg/assets')
  await page.getByLabel('Login',{exact:true}).fill('admin')
  await page.getByLabel('Password',{exact:true}).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button',{name:'Sign in',exact:true}).tap()
  await selectProject(page,project)
  const arm = results.locator('article[data-result-key*="code=DEMO_ARM"]').first()
  await arm.locator('strong').tap()
  await results.locator('h2',{hasText:'Robot Arm'}).waitFor()
  const objectHeader = results.locator('.mobile-result-header')
  await openObjectNotes()
  await inspector.getByLabel('Note text',{exact:true}).fill('Main header stays visible')
  await inspector.getByLabel('Insert emoji',{exact:true}).tap()
  const emoji = inspector.locator('.emoji-grid button').first()
  await emoji.waitFor()
  assert.equal(await emoji.evaluate(element=>getComputedStyle(element).fontSize),'32px')
  await page.screenshot({path:'../.screenshots/mobile-emoji-notes.png',animations:'disabled'})
  const glyph = await emoji.innerText()
  await emoji.tap()
  assert.ok((await inspector.getByLabel('Note text',{exact:true}).inputValue()).includes(glyph),'Emoji inserts into the note draft')
  await inspector.getByLabel('Note text',{exact:true}).fill('Main header stays visible')
  for (const button of await page.getByRole('button',{name:'Dismiss notification',exact:true}).all()) await button.tap()
  for (const width of [320,390,640]) {
    await page.setViewportSize({width,height:844})
    await geometry()
    await page.screenshot({path:'../.screenshots/mobile-inspector-page-'+width+'.png',animations:'disabled'})
  }
  await page.getByRole('button',{name:'Open navigation',exact:true}).tap()
  await page.getByRole('dialog',{name:'Workspace navigation',exact:true}).waitFor()
  await page.getByRole('button',{name:'Close navigation',exact:true}).first().tap()
  assert.equal(await dock.getByRole('button',{name:'Help',exact:true}).count(),1)
  await dock.getByRole('button',{name:'Help',exact:true}).tap()
  const help = page.locator('dialog.help-view[open]')
  await help.getByRole('button',{name:'Back',exact:true}).tap()
  await help.waitFor({state:'hidden'})
  await geometry()
  await dock.getByRole('button',{name:'Back',exact:true}).tap()
  await results.locator('h2',{hasText:'Robot Arm'}).waitFor()
  await openObjectNotes()
  assert.equal(await inspector.getByLabel('Note text',{exact:true}).inputValue(),'Main header stays visible','Returning preserves the Inspector draft')
  await inspector.getByLabel('Note text',{exact:true}).fill('')
  await dock.getByRole('button',{name:'Back',exact:true}).tap()
  await objectHeader.getByRole('button',{name:'Tasks',exact:true}).tap()
  await page.getByRole('dialog',{name:'Choose process',exact:true}).getByRole('menuitem',{name:/model/i}).tap()
  const manager = page.getByRole('region',{name:'Task Manager',exact:true})
  const card = manager.locator('.mobile-task-card').filter({hasText:'Robot Arm'}).first()
  await card.getByRole('button',{name:'Open notes',exact:true}).tap()
  await inspector.getByLabel('Note text',{exact:true}).waitFor()
  await geometry()
  await dock.getByRole('button',{name:'Back',exact:true}).tap()
  await card.waitFor()
  assert.equal(await dock.isVisible(),false,'Back returns to Task Manager when it opened Inspector')
  assert.deepEqual(errors,[])
  console.log('PASS mobile Inspector page: application header visible and interactive, 320/390/640 viewport containment, return to object or Task Manager, retained draft')
} catch(error) {
  await page.screenshot({path:'../.screenshots/mobile-inspector-page-failure.png',animations:'disabled'}).catch(()=>{})
  throw error
} finally { await browser.close() }
