import { selectProject, openViewActions } from './project_selection.mjs'
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1280, height: 800 }, hasTouch: true })
const page = await context.newPage(), errors = []
page.setDefaultTimeout(8000)
page.on('pageerror', error => errors.push(error.message))
try {
  await page.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode:'dark', language:'en' })))
  await page.goto(process.argv[2] + '/projects/admin/?search_type=sthpw/project&view=table')
  await page.getByLabel('Login', { exact: true }).fill('admin')
  await page.getByLabel('Password', { exact: true }).fill('private-test-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).tap()
  await selectProject(page, 'one')
  await page.locator('.navigation-toggle').tap()
  await page.locator('.type-list [data-search-type="contract/entity"]').tap()
  await page.getByLabel('Change search results view', { exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'Table', exact: true }).click()
  await openViewActions(page)
  const viewMenu = page.locator('details:has(> summary[aria-label="View actions"]) > .account-panel')
  assert.equal(await viewMenu.getByRole('button', { name:'Edit input definitions', exact:true }).evaluate(el => getComputedStyle(el.querySelector(':scope > span:not(.app-icon)')).whiteSpace), 'nowrap')
  if (process.argv[3]) await page.screenshot({ path:process.argv[3].replace('.png', '-desktop-menu.png'), animations:'disabled' })
  await viewMenu.getByRole('button', { name: 'Create record', exact: true }).tap()
  const form = page.getByRole('dialog', { name: 'Record form', exact: true })
  await form.getByRole('heading', { name: 'Create record', exact: true }).waitFor()
  const maximize = form.getByRole('button', { name:'Maximize window', exact:true }), close = form.getByRole('button', { name:'Close', exact:true })
  await maximize.waitFor()
  const maxBox = await maximize.boundingBox(), closeBox = await close.boundingBox()
  assert(closeBox.x - (maxBox.x + maxBox.width) < 12, 'Window buttons stay together at the right edge')
  assert.equal(await form.getByRole('heading', { name:'Create record', exact:true }).evaluate(el => getComputedStyle(el).fontSize), '16px')
  await maximize.click(); assert.equal((await form.boundingBox()).width, 1280)
  await form.getByRole('button', { name:'Restore window', exact:true }).click()
  if (process.argv[3]) await page.screenshot({ path:process.argv[3].replace('.png', '-desktop-dialog.png'), animations:'disabled' })
  await form.getByLabel('Name', { exact: true }).fill('Created from menu')
  await form.getByRole('button', { name: 'Save record', exact: true }).tap()
  await form.waitFor({ state: 'hidden' })
  await page.getByRole('cell', { name: 'Created from menu', exact: true }).waitFor()
  const row = page.getByRole('row').filter({ has:page.getByRole('cell', { name:'Created from menu', exact:true }) })
  await row.getByRole('button', { name:'Object actions', exact:true }).click()
  const actions = page.getByRole('dialog', { name:'Object actions', exact:true })
  await actions.waitFor()
  assert.equal(await actions.locator('header').count(), 0, 'Object actions use the shared menu, without dialog chrome')
  assert.equal(await actions.getByRole('button', { name:'Edit record', exact:true }).evaluate(el => parseFloat(getComputedStyle(el).height)), 32)
  if (process.argv[3]) await page.screenshot({ path:process.argv[3].replace('.png', '-desktop-context.png'), animations:'disabled' })
  await page.keyboard.press('Escape'); await actions.waitFor({ state:'hidden' })
  await row.click({ button:'right' }); await actions.waitFor()
  const menuBox = await actions.boundingBox()
  assert(menuBox.x >= 0 && menuBox.x + menuBox.width <= 1280 && menuBox.y + menuBox.height <= 800)
  await page.mouse.click(4, 4); await actions.waitFor({ state:'hidden' })
  await page.setViewportSize({ width: 320, height: 740 })
  await page.getByRole('button', { name: 'Create record', exact: true }).tap()
  await form.getByLabel('Name', { exact: true }).fill('Unsaved touch draft')
  await form.getByRole('button', { name: 'Close', exact: true }).tap()
  await form.getByRole('button', { name: 'Keep editing', exact: true }).tap()
  assert.equal(await form.getByLabel('Name', { exact: true }).inputValue(), 'Unsaved touch draft')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  if (process.argv[3]) await page.screenshot({ path: process.argv[3], animations: 'disabled' })
  await form.getByRole('button', { name: 'Save record', exact: true }).tap()
  await form.waitFor({ state: 'hidden' })
  await page.locator('.workspace-results .result-item-copy > strong').getByText('Unsaved touch draft', { exact: true }).waitFor()
  await page.route('**/admin/form', async route => {
    const response = await route.fetch(), body = await response.json()
    body.result.fields[0].options.unknown_widget_option = 'preserve'
    await route.fulfill({ response, json: body })
  })
  await page.getByRole('button', { name: 'Create record', exact: true }).tap()
  await form.getByText(/This form contains unsupported inputs/).waitFor()
  assert.equal(await form.getByLabel('Name', { exact: true }).isVisible(), true)
  assert.equal(await form.getByRole('button', { name: 'Save record', exact: true }).isDisabled(), true)
  await form.getByRole('button', { name: 'Close', exact: true }).tap()
  await page.unroute('**/admin/form')
  await selectProject(page, 'admin')
  await page.locator('.navigation-toggle').tap()
  await page.locator('.type-list [data-search-type="sthpw/search_object"]').tap()
  await page.getByRole('button', { name: 'Create record', exact: true }).tap()
  await form.getByLabel('Search Type', { exact: true }).fill('contract/browser_color_form')
  await form.getByLabel('Namespace', { exact: true }).fill('contract')
  await form.getByLabel('Database', { exact: true }).fill('{project}')
  await form.getByLabel('Table Name', { exact: true }).fill('browser_color_form')
  await form.getByLabel('Class Name', { exact: true }).fill('pyasm.search.SObject')
  await form.getByLabel('Choose color for Color', { exact: true }).tap()
  const color = page.getByRole('dialog', { name: 'Choose a color', exact: true })
  await color.getByLabel('Color in HEX format').fill('#234abc')
  await color.getByRole('button', { name: 'OK', exact: true }).tap()
  assert.equal(await form.getByLabel('Choose color for Color', { exact: true }).getAttribute('title'), '#234abc')
  await form.getByLabel('Choose color for Color', { exact: true }).tap()
  assert.equal(await color.getByLabel('Color in HEX format').inputValue(), '#234abc')
  await color.getByLabel('Color in HEX format').fill('#345bcd')
  await color.getByRole('button', { name: 'OK', exact: true }).tap()
  assert.equal(await form.getByLabel('Choose color for Color', { exact: true }).getAttribute('title'), '#345bcd')
  assert.equal(await form.getByRole('alert').count(), 0)
  assert.equal(await form.getByRole('button', { name: 'Save record', exact: true }).isEnabled(), true)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  if (process.argv[3]) await page.screenshot({ path: process.argv[3].replace('object-creation-touch', 'search-object-creation-touch'), animations: 'disabled' })
  const saved = page.waitForResponse(response => response.url().endsWith('/admin/rpc') && response.request().postData()?.includes('tactic.ui.panel.EditCmd'))
  await form.getByRole('button', { name: 'Save record', exact: true }).tap()
  const response = await saved, result = await response.json()
  assert.equal(response.status(), 200)
  assert.equal(result.result.info.sobject.color, '#345bcd')
  assert.equal(result.result.info.sobject.search_type, 'contract/browser_color_form')
  await form.waitFor({ state: 'hidden' })
  assert.deepEqual(errors, [])
  console.log('object creation: menu, footer, touch draft, native search_object form and color save passed')
} catch (error) { console.error(errors); console.error((await page.locator('body').innerText()).slice(0, 2000)); throw error } finally { await browser.close() }

