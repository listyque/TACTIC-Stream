import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { selectProject } from './project_selection.mjs'

const browser = await chromium.launch({headless:true})
const page = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
page.setDefaultTimeout(15000)
const project = process.env.STREAM_CHECK_PROJECT, base = process.argv[2], errors = [], failures = [], reports = []
page.on('pageerror',error => errors.push(error.message))
page.on('response',async response => {
  if (response.status() >= 400) failures.push([response.url(),await response.text().catch(()=> '')])
  if (response.url().endsWith('/admin/rpc') && response.request().method() === 'POST' && response.request().postDataJSON()?.method === 'log') reports.push({status:response.status(),payload:response.request().postDataJSON()})
})
const queue = page.locator('.commit-queue:visible')
try {
  await page.addInitScript(() => {
    if (!localStorage.getItem('tactic_stream.appearance')) localStorage.setItem('tactic_stream.appearance',JSON.stringify({mode:'dark',language:'en'}))
    localStorage.setItem('tactic_stream.preferences',JSON.stringify({checkin:{commitQueueAutoClean:false}}))
    localStorage.setItem('tactic_stream.debug_log',JSON.stringify({recordingLevels:[]}))
  })
  await page.goto(base+'/projects/'+project+'/?search_type=cg/assets')
  await page.getByLabel('Login',{exact:true}).fill('admin')
  await page.getByLabel('Password',{exact:true}).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button',{name:'Sign in',exact:true}).tap()
  await selectProject(page,project)
  const arm = page.locator('.mobile-result-screen article[data-result-key*="code=DEMO_ARM"]').first()
  await arm.getByRole('button',{name:'Add files',exact:true}).tap()
  const checkin = page.getByRole('dialog',{name:'Save snapshot',exact:true})
  await checkin.getByLabel('Context',{exact:true}).waitFor()
  const image = await page.screenshot({clip:{x:0,y:0,width:32,height:32}})
  await checkin.locator('input[type=file]').setInputFiles({name:'mobile-image.png',mimeType:'image/png',buffer:image})
  await checkin.getByRole('button',{name:'Add to Commit Queue',exact:true}).tap()
  await queue.locator('.queue-row').waitFor()
  assert.equal(await queue.locator('.queue-source-files').isVisible(),false,'Mobile list does not duplicate a desktop files pane')
  assert.equal(await queue.getByRole('textbox',{name:'Description',exact:true}).isVisible(),false,'Parameters stay collapsed initially')
  await queue.locator('.queue-row-status').getByText('Ready to send',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Back to search',exact:true}).tap()
  await arm.getByRole('button',{name:'Add files',exact:true}).tap()
  await checkin.getByLabel('Context',{exact:true}).waitFor()
  await checkin.locator('input[type=file]').setInputFiles({name:'mobile-image.png',mimeType:'image/png',buffer:image})
  await checkin.getByRole('button',{name:'Add to Commit Queue',exact:true}).tap()
  await queue.locator('.queue-duplicate').waitFor()
  await queue.getByRole('button',{name:'Ignore duplicate',exact:true}).tap()
  assert.equal(await queue.locator('.queue-row').count(),1,'Duplicate decision must work without expanding details')
  for (const width of [320,390]) {
    await page.setViewportSize({width,height:844})
    const footer = await queue.locator('.queue-send').boundingBox()
    assert.ok(footer.y+footer.height <= page.viewportSize().height+1,'Send stays within the mobile viewport')
    assert.equal(await queue.evaluate(element=>element.scrollWidth>element.clientWidth),false)
    await page.screenshot({path:'../.screenshots/mobile-commit-queue-ready-'+width+'.png',animations:'disabled'})
  }
  await page.route('**/UploadServer/',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'Mobile upload temporarily unavailable'})}))
  await queue.getByRole('button',{name:'Commit all',exact:true}).tap()
  await queue.locator('.queue-row-error').filter({hasText:'Mobile upload temporarily unavailable'}).waitFor()
  await queue.locator('.queue-row-status').getByText('Failed',{exact:true}).waitFor()
  await page.screenshot({path:'../.screenshots/mobile-commit-queue-error.png',animations:'disabled'})
  await page.unroute('**/UploadServer/')
  failures.length = 0
  await queue.getByRole('button',{name:'Retry',exact:true}).tap()
  await page.waitForFunction(() => [...document.querySelectorAll('.queue-row-status')].some(element => /Complete|Failed|Result unknown/.test(element.textContent)),{},{timeout:30000})
  const row = queue.locator('.queue-row').first()
  assert.match(await row.locator('.queue-row-status').textContent(),/Complete/,'Image check-in must complete: '+JSON.stringify(failures))
  assert.deepEqual(errors,[])
  assert.deepEqual(failures,[])
  const session = await page.evaluate(() => JSON.parse(localStorage.getItem('tactic_stream.session') || sessionStorage.getItem('tactic_stream.session')))
  async function rpc(method,args=[],kwargs={}) {
    const response = await page.request.post(base+'/admin/rpc',{data:{method,args:[{ticket:session.ticket,project},...args],kwargs}})
    assert.equal(response.status(),200,await response.text())
    return (await response.json()).result
  }
  const diagnostic = reports.find(row=>row.payload.args[2].includes('Mobile upload temporarily unavailable'))
  assert.equal(diagnostic?.status,200,'The browser error must reach the native database logger')
  assert.ok(!diagnostic.payload.args[2].includes(session.ticket),'Database diagnostics must redact tickets')
  const runtimeLog = page.waitForResponse(response => response.url().endsWith('/admin/rpc') && response.request().postData()?.includes('Mobile runtime diagnostic'))
  await page.evaluate(() => console.error(new Error('Mobile runtime diagnostic')))
  assert.equal((await runtimeLog).status(),200,'JavaScript errors use the same authenticated database logger')
  const snapshot = await rpc('get_snapshot',['cg/assets?project='+project+'&code=DEMO_ARM'],{context:'publish',version:2})
  assert.equal(snapshot.version,2,'The original snapshot must be kept and the upload saved as a new version')
  const response = await page.request.post(base+'/admin/navigation-link',{data:{ticket:session.ticket,project,link:'skey://'+snapshot.__search_key__}})
  assert.equal(response.status(),200,await response.text())
  const target = (await response.json()).result
  const file = target.preview.files.find(file => file.type === 'main')
  assert.ok(file?.href,'The saved image must be downloadable')
  assert.deepEqual(await (await page.request.get(new URL(file.href,base).href)).body(),image,'Saved original image bytes must match')
  const first = await rpc('get_snapshot',['cg/assets?project='+project+'&code=DEMO_ARM'],{context:'publish',version:1})
  assert.equal(first.version,1,'Retry must not replace the earlier numbered version')
  const bar = await page.locator('.topbar').boundingBox(), bounds = await queue.boundingBox()
  assert.ok(bounds.y >= bar.y+bar.height,'Mobile Queue keeps the main application header visible')
  const dismiss = page.getByRole('button',{name:'Dismiss notification',exact:true})
  while (await dismiss.count()) await dismiss.first().tap()
  await queue.getByRole('button',{name:'Check-in details',exact:true}).tap()
  await queue.getByRole('textbox',{name:'Description',exact:true}).waitFor()
  await queue.locator('.queue-source-files').waitFor()
  await queue.getByRole('button',{name:'Check-in details',exact:true}).tap()
  await page.screenshot({path:'../.screenshots/mobile-commit-queue-complete.png',animations:'disabled'})
  await page.evaluate(() => localStorage.setItem('tactic_stream.appearance',JSON.stringify({mode:'dark',language:'ru'})))
  await page.reload()
  await queue.locator('.queue-row').waitFor()
  for (const width of [320,390]) {
    await page.setViewportSize({width,height:844})
    await queue.locator('.queue-send > .workspace-menu > summary').tap()
    await page.getByRole('button',{name:'Очистить очередь',exact:true}).waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await queue.evaluate(element=>element.scrollWidth>element.clientWidth),false)
    await page.screenshot({path:'../.screenshots/mobile-commit-queue-ru-'+width+'.png',animations:'disabled'})
  }
  console.log('PASS mobile Commit Queue: genuine PNG upload and check-in, numbered version preserved, no browser/server errors, page below application header')
} catch(error) {
  console.error(error,errors,failures)
  await page.screenshot({path:'../.screenshots/mobile-commit-queue-failure.png',animations:'disabled'}).catch(()=>{})
  throw error
} finally { await browser.close() }
