const packed = packTagRows(Array.from({ length: 1500 }, (_, n) => ({ tag: 'token' + n, weight: n / 1500 })), 280, text => text.length * 10, 'ALL')
assert.equal(packed.flatMap(row => row.cells).length, 1501)
assert(packed.every((row, index) => row.width <= 280 && (!index || row.top === packed[index - 1].top + packed[index - 1].height + 8)))
assert(packed.every((row, index) => tagRowAt(packed, row.top) === index))
assert.deepEqual(packTagRows([], 280, () => 20, 'ALL'), [])

