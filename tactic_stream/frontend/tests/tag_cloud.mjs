const localSearch = cloud.getByRole('searchbox', { name: 'Search tags' })
const range = page.locator('.workspace-footer .result-range')
async function navigate(type) {
  await page.locator('.navigation-toggle').click()
  await page.locator(`.type-list button[data-search-type="${type}"]`).last().click()
  await ready()
}
async function open() {
  await cloud.locator('summary').click()
  await page.waitForFunction(() => document.querySelector('.tag-cloud-viewport')?.getAttribute('aria-busy') === 'false' && document.querySelector('.tag-cloud > summary')?.getAttribute('aria-expanded') === 'true')
}
async function choose(tag, count) {
  const response = page.waitForResponse(response => response.url().endsWith('/admin/search-configuration/query'))
  await cloud.getByRole('button', { name: tag, exact: true }).click()
  await response; await ready()
  assert.match(await range.innerText(), new RegExp('of ' + count + '$'))
  assert.equal(await cloud.locator('summary').getAttribute('aria-expanded'), 'true')
}
