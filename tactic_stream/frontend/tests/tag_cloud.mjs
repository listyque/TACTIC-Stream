const errors = [], catalogs = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error' && !message.text().includes('status of 500')) errors.push(message.text()) })
page.on('request', request => { if (request.url().endsWith('/admin/search-configuration/tags')) catalogs.push(request.postDataJSON()) })
