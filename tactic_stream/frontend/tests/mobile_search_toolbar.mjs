import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { selectProject } from './project_selection.mjs'

const browser = await chromium.launch({headless:true})
const page = await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:process.env.STREAM_CHECK_STALE_SECTION_CSS?3:1})
page.setDefaultTimeout(12000)
const errors = []
page.on('pageerror',error=>errors.push(error.message))
const toolbar = page.locator('.workspace-browser > .workspace-tabs')
const search = page.getByRole('combobox',{name:'Search objects',exact:true})
const tabs = toolbar.locator('.workspace-tab-menu')
const more = toolbar.locator('.compact-result-actions')
async function ready() { await page.waitForFunction(()=>document.querySelector('.workspace-results')?.getAttribute('aria-busy')==='false') }
async function count(value) { await page.waitForFunction(value=>document.querySelectorAll('.configured-view[data-workspace-current="true"] .mobile-result-screen .result-item-object').length===value,value) }
async function tabMenu() { await tabs.locator('> summary').tap() }
try {
  if (process.env.STREAM_CHECK_STALE_SECTION_CSS) await page.route('**/ui/assets/*.css',async route => {
    const response = await route.fetch()
    const css = (await response.text()).replace(/[^{}]*\.mobile-section[^{}]*\{[^{}]*\}/g,'')
    await route.fulfill({response,body:css})
  })
  await page.addInitScript(()=>{ if(!localStorage.getItem('tactic_stream.appearance')) localStorage.setItem('tactic_stream.appearance',JSON.stringify({mode:'dark',language:'en'})) })
  await page.goto(process.argv[2]+'/projects/'+process.env.STREAM_CHECK_PROJECT+'/?search_type=cg/assets')
  await page.getByLabel('Login',{exact:true}).fill('admin')
  await page.getByLabel('Password',{exact:true}).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button',{name:'Sign in',exact:true}).tap()
  await selectProject(page,process.env.STREAM_CHECK_PROJECT)
  await ready()
  const initialItems = page.locator('.configured-view[data-workspace-current="true"] .mobile-result-screen .result-item-object')
  await initialItems.first().waitFor()
  const initialCount = await initialItems.count()
  const badge = tabs.locator('> summary > .mobile-section-badge')
  const assetColor = await badge.evaluate(node=>getComputedStyle(node).getPropertyValue('--preview-accent'))
  assert.ok(assetColor,'Current section uses its saved accent')
  assert.equal(await badge.locator('.app-icon').count(),1)
  await page.getByRole('button',{name:'Open navigation',exact:true}).tap()
  const textureLink = page.locator('.type-list button[data-search-type="cg/texture"]').last()
  const textureTitle = await textureLink.getAttribute('aria-label')
  await textureLink.tap();await ready()
  await page.locator('.mobile-result-list article[data-result-key*="DEMO_TEX_METAL"]').first().waitFor()
  const textureColor = await badge.evaluate(node=>getComputedStyle(node).getPropertyValue('--preview-accent'))
  assert.notEqual(textureColor,assetColor,'Section switch updates the coloured circle on the title button')
  await tabMenu()
  const sectionChoices = tabs.locator('.mobile-section-choice')
  const assets = sectionChoices.filter({has:page.getByText('Assets',{exact:true})}),texture = sectionChoices.filter({has:page.getByText(textureTitle,{exact:true})})
  await assets.waitFor()
  assert.equal(await assets.locator('.mobile-section-badge').evaluate(node=>getComputedStyle(node).getPropertyValue('--preview-accent')),assetColor)
  assert.equal(await texture.locator('.mobile-section-badge').evaluate(node=>getComputedStyle(node).getPropertyValue('--preview-accent')),textureColor)
  assert.equal(await texture.getAttribute('aria-checked'),'true')
  for (const circle of await tabs.locator('.mobile-section-badge').all()) {
    const size = await circle.evaluate(node=>{const style=getComputedStyle(node);return {width:style.width,height:style.height,radius:style.borderRadius}})
    assert.equal(size.width,'24px','Every section circle stays compact even with cached CSS')
    assert.equal(size.height,'24px')
    assert.equal(size.radius,'50%')
  }
  await tabs.locator('> summary .control-ripple-clip').waitFor({state:'hidden'})
  const shot = await page.screenshot({path:'../.screenshots/mobile-section-circles-menu'+(process.env.STREAM_CHECK_STALE_SECTION_CSS?'-stale-3x':'')+'.png',animations:'disabled'})
  assert.equal(shot.readUInt32BE(16),process.env.STREAM_CHECK_STALE_SECTION_CSS?1170:390,'Menu also renders at the actual device pixel scale')
  await assets.tap();await ready();await count(initialCount)
  await page.keyboard.press('Escape')
  assert.equal(await badge.evaluate(node=>getComputedStyle(node).getPropertyValue('--preview-accent')),assetColor)
  for (const width of [320,390]) {
    await page.setViewportSize({width,height:844})
    assert.equal(await search.isVisible(),false,'Search stays collapsed initially')
    assert.ok((await toolbar.boundingBox()).height<=40,'One compact toolbar replaces search and tab rows')
    assert.equal(await toolbar.locator('.workspace-tab-list').isVisible(),false)
    const title = tabs.locator('> summary')
    const circle = await badge.boundingBox()
    assert.equal(circle.width,24);assert.equal(circle.height,24)
    assert.equal(await badge.evaluate(node=>getComputedStyle(node).borderRadius),'50%')
    const radius = await title.evaluate(node=>getComputedStyle(node).borderRadius)
    assert.ok(parseFloat(radius)>0 && parseFloat(radius)<=16 && radius.endsWith('px'),'The title has soft corners without an elliptical outline')
    await title.hover()
    assert.equal(await title.evaluate(node=>getComputedStyle(node).borderRadius),radius)
    await page.screenshot({path:'../.screenshots/mobile-search-toolbar-hover-'+width+'.png',animations:'disabled'})
    const box = await title.boundingBox()
    await page.mouse.move(box.x+box.width/2,box.y+box.height/2)
    await page.mouse.down()
    assert.equal(await title.evaluate(node=>getComputedStyle(node).borderRadius),radius)
    await page.mouse.up()
    await tabs.locator('.workspace-tab-menu-items').getByRole('menuitemradio',{name:'Assets',exact:true}).waitFor()
    await page.keyboard.press('Escape')
    await title.focus()
    assert.equal(await title.evaluate(node=>getComputedStyle(node).borderRadius),radius)
    await title.evaluate(node=>node.blur())
    await page.mouse.move(0,0)
    assert.equal(await page.locator('.workspace-footer > .create-object').count(),0,'Creation is available in the menu without a duplicate floating button')
    await page.screenshot({path:'../.screenshots/mobile-search-toolbar-'+width+'.png',animations:'disabled'})
  }
  await toolbar.getByRole('button',{name:'Open search',exact:true}).tap()
  await page.screenshot({path:'../.screenshots/mobile-search-toolbar-expanded.png',animations:'disabled'})
  await search.fill('Robot Arm')
  await search.press('Enter'); await ready()
  assert.equal(await search.isVisible(),false,'Submitting returns space to the results')
  await page.locator('.mobile-result-screen article[data-result-key*="code=DEMO_ARM"]').waitFor()
  await count(1)
  await tabMenu()
  await tabs.getByRole('button',{name:'Add new search tab',exact:true}).tap(); await ready()
  assert.equal(await toolbar.locator('.mobile-tab-count').innerText(),'2')
  await tabMenu()
  await tabs.getByRole('menuitemradio',{name:'Robot Arm',exact:true}).tap(); await ready()
  await count(1)
  await tabMenu()
  await tabs.getByRole('menuitem',{name:'Close search tab: Robot Arm',exact:true}).tap(); await ready()
  await tabMenu()
  await tabs.getByRole('menuitem',{name:'Robot Arm',exact:true}).tap(); await ready()
  assert.equal(await toolbar.locator('.mobile-tab-count').innerText(),'2','Closed tabs are restored from the same title menu')
  await toolbar.getByRole('button',{name:'Open search',exact:true}).tap()
  assert.equal(await search.inputValue(),'Robot Arm')
  await search.press('Escape')
  assert.equal(await search.isVisible(),false)
  await more.locator('> summary').tap()
  await more.getByRole('button',{name:'Clear search',exact:true}).tap(); await count(initialCount); await ready()
  await more.locator('> summary').tap()
  await more.getByLabel('Quick filters',{exact:true}).tap()
  await page.getByText('Filter by field',{exact:true}).tap()
  await page.getByLabel('Filter field',{exact:true}).selectOption('code')
  await page.getByLabel('Filter value',{exact:true}).fill('DEMO_ARM')
  await page.getByRole('button',{name:'Apply filters',exact:true}).tap(); await ready()
  await count(1)
  await more.locator('> summary').tap()
  await more.getByRole('button',{name:'Clear search',exact:true}).tap(); await count(initialCount); await ready()
  await more.locator('> summary').tap()
  await more.getByRole('button',{name:'Tags',exact:true}).tap()
  await page.locator('.tag-cloud .account-panel:popover-open').waitFor()
  await page.screenshot({path:'../.screenshots/mobile-search-toolbar-tags.png',animations:'disabled'})
  await page.keyboard.press('Escape')
  await more.locator('> summary').tap()
  await more.getByRole('button',{name:'Saved searches',exact:true}).tap()
  const library = page.getByRole('dialog',{name:'Saved searches',exact:true})
  await library.waitFor()
  await library.getByRole('button',{name:'Back',exact:true}).tap()
  await library.waitFor({state:'hidden'})
  await page.evaluate(()=>localStorage.setItem('tactic_stream.appearance',JSON.stringify({mode:'dark',language:'ru'})))
  await page.reload(); await ready(); await count(initialCount)
  await page.screenshot({path:'../.screenshots/mobile-search-toolbar-ru.png',animations:'disabled'})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.setViewportSize({width:1440,height:950})
  await page.getByRole('combobox',{name:'Поиск объектов',exact:true}).waitFor()
  await toolbar.locator('.workspace-tab-list').waitFor()
  const desktopTabs = toolbar.locator('[role="tab"]')
  assert.equal(await desktopTabs.count(),2)
  await desktopTabs.first().click(); await ready()
  await desktopTabs.last().click(); await ready()
  await toolbar.getByRole('button',{name:'Добавить вкладку поиска',exact:true}).click(); await ready()
  assert.equal(await desktopTabs.count(),3,'Desktop still adds and switches ordinary tabs')
  assert.deepEqual(errors,[])
  console.log('PASS mobile search toolbar: collapsed search, native query/filter, stateful tabs/close/restore, Tags, Saved searches, RU, desktop restoration')
} catch(error) {
  await page.screenshot({path:'../.screenshots/mobile-search-toolbar-failure.png',animations:'disabled'}).catch(()=>{})
  throw error
} finally { await browser.close() }
