import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { chromium } from 'playwright'

const base = process.argv[2], project = process.env.STREAM_CHECK_PROJECT
const native = JSON.parse(readFileSync(new URL('../../.screenshots/handler-current/system-activity-geometry.json', import.meta.url)))
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'dark', hasTouch: true })
  page.setDefaultTimeout(12000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => { if (!localStorage.getItem('tactic_stream.appearance')) localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode: 'dark', language: 'en' })) })
  await page.goto(base + '/projects/admin/?search_type=sthpw/project&view=table')
  await page.getByLabel('Login', { exact: true }).fill(process.env.STREAM_CHECK_LOGIN || 'admin')
  await page.getByLabel('Password', { exact: true }).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.locator('.topbar').waitFor()
  await page.goto(base + '/projects/' + encodeURIComponent(project) + '/?' + new URLSearchParams({ search_type: 'sthpw/search_object', view: 'table' }))
  await page.waitForFunction(() => document.querySelector('.workspace-results')?.getAttribute('aria-busy') === 'false')
  const menu = async name => { await page.getByLabel('More options', { exact: true }).click(); await page.locator('.settings-menu').getByRole('button', { name, exact: true }).click() }
  await menu('Save Preferences')
  let message = 'Unable to reach the server.'
  await page.route('**/admin/rpc', route => route.request().postDataJSON().method === 'ping'
    ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: message }) }) : route.continue())
  const ping = async () => {
    await page.getByLabel('Connection', { exact: true }).click()
    await Promise.all([page.waitForResponse(response => response.url().endsWith('/admin/rpc') && response.request().postDataJSON()?.method === 'ping'),
      page.getByRole('button', { name: 'Ping now', exact: true }).click()])
    await page.waitForFunction(() => !document.querySelector('.system-activity-control .busy-indicator.running'))
    await page.keyboard.press('Escape')
  }
  await ping()
  await page.getByLabel('System activity', { exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Notifications', exact: true })
  const rows = dialog.locator('.system-activity-event'), filters = dialog.getByRole('radiogroup')
  await rows.filter({ hasText: 'Preferences saved' }).waitFor()
  await dialog.getByLabel('Maximize window', { exact: true }).click()
  const near = (actual, expected, label, tolerance = 2) => assert(Math.abs(actual - expected) <= tolerance, `${label}: ${actual} vs Qt ${expected}`)
  for (const reference of native) {
    // Match Qt content, accounting for the shared web title bar/border and compact-host margins.
    const margin = reference.width + 2 <= 760 ? 16 : 0
    await page.setViewportSize({ width: reference.width + 2 + margin, height: reference.height + 42 + margin })
    await page.waitForFunction(width => document.querySelector('.system-activity-content')?.clientWidth === width, reference.width)
    const compact = reference.width < 760
    await page.waitForFunction(compact => !!document.querySelector('.system-activity-dialog [role="radio"].icon-button') === compact, compact)
    const panel = dialog.locator('.activity-feed-panel'), toolbar = dialog.locator('.activity-feed-toolbar')
    near((await panel.boundingBox()).width, reference.notificationsPanel.width, 'Panel width')
    near((await toolbar.boundingBox()).width, reference.notificationsToolbar.width, 'Toolbar width')
    near((await toolbar.boundingBox()).height, reference.notificationsToolbar.height, 'Toolbar height')
    const row = rows.filter({ hasText: 'Preferences saved' })
    const bounds = await row.boundingBox(), title = await row.locator('strong').boundingBox(), stamp = await row.locator('time').boundingBox()
    near(bounds.width, reference.rows[2].width, 'History row width')
    near(bounds.height, reference.rows[2].height, 'History row height')
    assert.equal(await row.locator('header').evaluate(node => getComputedStyle(node).gridTemplateColumns.split(' ').length), bounds.width < 620 ? 1 : 2)
    assert(bounds.width < 620 ? stamp.y > title.y : Math.abs(stamp.y - title.y) < 1)
    const rail = await row.evaluate(node => { const style = getComputedStyle(node, '::after'); return [style.width, style.top, style.bottom] })
    assert.deepEqual(rail, ['3px', '6px', '6px'])
    assert(await row.locator('time').getAttribute('title') !== await row.locator('time').getAttribute('datetime'))
    assert.equal(await filters.locator('button > span:not(.app-icon)').count(), compact ? 0 : 4)
    assert.equal(await filters.locator('.app-icon').count(), 4)
    assert.equal(await filters.getByRole('radio', { name: 'Server', exact: true }).getAttribute('title'), compact ? 'Server' : null)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.screenshot({ path: `../.screenshots/handler-current/stream-notification-history-${reference.width}.png`, animations: 'disabled' })
  }
  await filters.getByRole('radio', { name: 'Client', exact: true }).press('Home')
  assert.equal(await filters.getByRole('radio', { name: 'All', exact: true }).getAttribute('aria-checked'), 'true')
  await filters.getByRole('radio', { name: 'Check-in', exact: true }).tap()
  assert.equal(await rows.count(), 0)
  const empty = dialog.locator('.system-activity-empty')
  assert.equal(await empty.locator('.app-icon').evaluate(node => getComputedStyle(node).fontSize), '30px')
  await page.screenshot({ path: '../.screenshots/handler-current/stream-notification-history-empty-320.png', animations: 'disabled' })
  await dialog.getByLabel('Close Notifications', { exact: true }).tap()
  await page.setViewportSize({ width: 1440, height: 1000 })
  for (let index = 0; index < 14; index++) { message = 'History event ' + index; await ping() }
  message = 'Long server message\n' + 'Select this diagnostic text. '.repeat(16) + '\nhttps://example.com/help <img src=x onerror=alert(1)>'
  await ping()
  await page.getByLabel('System activity', { exact: true }).click()
  await filters.getByRole('radio', { name: 'All', exact: true }).click()
  const scroll = dialog.locator('.system-activity-history')
  await rows.filter({ hasText: 'Long server message' }).waitFor()
  assert(await scroll.evaluate(node => node.scrollHeight > node.clientHeight))
  assert.equal(await rows.locator('img').count(), 0)
  assert.equal(await rows.getByRole('link', { name: 'https://example.com/help', exact: true }).getAttribute('rel'), 'noopener noreferrer')
  assert.notEqual(await rows.locator('strong').first().evaluate(node => getComputedStyle(node).userSelect), 'none')
  await scroll.hover(); await page.mouse.wheel(0, 600)
  await page.waitForFunction(() => document.querySelector('.system-activity-history').scrollTop > 0)
  for (const width of [360, 320]) {
    await page.setViewportSize({ width, height: 740 })
    assert(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth))
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.screenshot({ path: `../.screenshots/handler-current/stream-notification-history-touch-${width}.png`, animations: 'disabled' })
  }
  await dialog.getByLabel('Clear history', { exact: true }).click()
  assert.equal(await rows.count(), 0)
  assert(await dialog.getByLabel('Clear history', { exact: true }).isDisabled())
  await dialog.getByLabel('Close Notifications', { exact: true }).click()
  await page.unroute('**/admin/rpc')
  await page.evaluate(() => { const settings = JSON.parse(localStorage.getItem('tactic_stream.appearance')); settings.language = 'ru'; settings.mode = 'light'; localStorage.setItem('tactic_stream.appearance', JSON.stringify(settings)) })
  await page.reload()
  await page.locator('.topbar').waitFor()
  await page.waitForFunction(() => !document.querySelector('.system-activity-control .busy-indicator.running'))
  const ru = JSON.parse(readFileSync(new URL('../src/locales/ru.json', import.meta.url)))
  await page.getByLabel(ru['More options'], { exact: true }).click()
  await page.locator('.settings-menu').getByRole('button', { name: ru['Save Preferences'], exact: true }).click()
  await page.getByLabel(ru['More options'], { exact: true }).click()
  await page.locator('.settings-menu').getByRole('button', { name: ru['System activity'], exact: true }).click()
  const russian = page.getByRole('dialog', { name: ru['Notifications'], exact: true })
  await russian.locator('.system-activity-event').getByText(ru['Preferences saved'], { exact: true }).waitFor()
  assert((await russian.locator('.system-activity-event').filter({ hasText: ru['Preferences saved'] }).locator('time').getAttribute('title')).includes('октября'))
  assert.equal(await russian.getByRole('radio').count(), 4)
  assert(await russian.evaluate(node => node.scrollWidth <= node.clientWidth))
  await page.screenshot({ path: '../.screenshots/handler-current/stream-notification-history-ru-light-320.png', animations: 'disabled' })
  assert.deepEqual(errors, [])
  console.log('PASS: current Qt history geometry, window/row thresholds, compact tooltips, keyboard filters, full dates, empty state, selectable safe links, scrolling and clear')
} finally { await browser.close() }
