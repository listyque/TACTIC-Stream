import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { selectProject } from './project_selection.mjs'

const base = process.argv[2], project = process.env.STREAM_CHECK_PROJECT
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1000, height: 740 }, hasTouch: true, colorScheme: 'dark' })
  page.setDefaultTimeout(12000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode: 'dark', language: 'en' })))
  await page.goto(base + '/projects/admin/?search_type=sthpw/project&view=table')
  await page.getByLabel('Login', { exact: true }).fill(process.env.STREAM_CHECK_LOGIN || 'admin')
  await page.getByLabel('Password', { exact: true }).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await selectProject(page, project)
  const ready = () => page.waitForFunction(() => document.querySelector('.workspace-results')?.getAttribute('aria-busy') === 'false')
  for (const type of ['cg/assets', 'cg/textures', 'cg/scenes', 'cg/shot']) {
    await page.goto(base + '/projects/' + encodeURIComponent(project) + '/?' + new URLSearchParams({ search_type: type, view: 'table' }))
    await ready()
  }
  const rail = page.locator('.section-tab-rail'), rows = rail.locator('.section-tab-row'), popup = page.locator('.section-tab-reveal')
  const order = () => rows.evaluateAll(nodes => nodes.map(node => node.dataset.sectionId))
  const initial = await order()
  assert(initial.length >= 4)
  const selected = await rail.locator('[aria-selected="true"]').getAttribute('aria-label')
  const search = page.getByLabel('Search objects', { exact: true })
  await search.fill('section drag draft')
  const workspace = await page.locator('.workspace-main').boundingBox()
  async function begin(from, to) {
    await rows.nth(from).getByRole('tab').hover()
    await page.waitForFunction(() => document.querySelector('.section-tab-reveal')?.matches(':popover-open'))
    await page.waitForTimeout(80)
    const origin = await rows.nth(from).boundingBox(), target = await rows.nth(to).boundingBox()
    const button = popup.locator('.section-tab-expanded'), bounds = await button.boundingBox()
    await page.mouse.move(bounds.x + 80, bounds.y + bounds.height / 2); await page.mouse.down()
    await page.mouse.move(bounds.x + 80, bounds.y + bounds.height / 2 + 3)
    assert.equal(await rail.locator('.dragging').count(), 0)
    await page.mouse.move(bounds.x + 80, target.y + target.height / 2, { steps: 6 })
    await rail.locator('.dragging').waitFor()
    await page.waitForTimeout(80)
    const state = await rows.evaluateAll(nodes => nodes.map(node => ({ y: parseFloat(node.style.getPropertyValue('--section-drag-y')), scale: getComputedStyle(node).scale })))
    const neighbour = from < to ? from + 1 : from - 1
    assert.equal(state[neighbour].y, from < to ? -45 : 45)
    assert.equal(state[from].scale, 'none', 'Native vertical tabs do not scale')
    assert(Math.abs((await popup.boundingBox()).y - origin.y - state[from].y - 2) < 1)
    assert.deepEqual(await page.locator('.workspace-main').boundingBox(), workspace, 'Revealed rail overlays the workspace')
  }
  await rows.first().getByRole('tab').hover()
  await page.waitForFunction(() => document.querySelector('.section-tab-reveal')?.matches(':popover-open'))
  await page.waitForTimeout(80)
  assert.equal((await popup.boundingBox()).width, 256)
  const titleBounds = await popup.locator('.section-tab-title').boundingBox()
  assert.equal(Math.round(titleBounds.x), 51, 'Native title starts at 51px from the rail origin')
  assert.equal(await popup.locator('.section-tab-expanded').evaluate(node => getComputedStyle(node).backgroundColor), 'rgba(0, 0, 0, 0)', 'ItemSurface owns the state layer')
  await page.screenshot({ path: '../.screenshots/handler-current/stream-section-rail-hover.png' })
  await begin(0, 2)
  assert.deepEqual(await order(), initial, 'No commit before pointer release')
  await page.screenshot({ path: '../.screenshots/handler-current/stream-section-rail-drag.png' })
  await page.mouse.up()
  const moved = [...initial]; moved.splice(2, 0, moved.splice(0, 1)[0])
  assert.deepEqual(await order(), moved)
  await page.waitForTimeout(80)
  assert(Math.abs((await popup.boundingBox()).y - (await rows.nth(2).boundingBox()).y - 2) < 1, 'Reveal remains aligned after drop')
  assert.equal(await rail.locator('[aria-selected="true"]').getAttribute('aria-label'), selected)
  assert.equal(await search.inputValue(), 'section drag draft')
  await page.reload(); await ready()
  assert.deepEqual(await order(), moved, 'Section order survives reload')
  assert.equal(await search.inputValue(), 'section drag draft')
  await begin(2, 0); await page.mouse.up()
  assert.deepEqual(await order(), initial)
  await begin(0, 2); await page.keyboard.press('Escape'); await page.mouse.up()
  assert.deepEqual(await order(), initial, 'Escape cancels section reorder')
  await begin(0, 2)
  await page.setViewportSize({ width: 1000, height: 720 })
  await page.waitForTimeout(80)
  await page.mouse.up()
  assert.deepEqual(await order(), initial, 'Resize cancels section reorder without committing')
  assert.equal(await popup.evaluate(node => node.matches(':popover-open')), false, 'Resize dismisses the dragged reveal')
  await page.setViewportSize({ width: 1000, height: 740 })
  await rows.first().getByRole('tab').hover()
  await page.waitForFunction(() => document.querySelector('.section-tab-reveal')?.matches(':popover-open'))
  await popup.getByRole('button', { name: 'Close tab', exact: true }).click()
  assert.equal(await rows.count(), initial.length - 1, 'A new close click is not swallowed after cancellation')
  assert.equal(await search.inputValue(), 'section drag draft', 'Closing the inactive section preserves the active draft')
  await rows.first().getByRole('tab').hover()
  await page.waitForFunction(() => document.querySelector('.section-tab-reveal')?.matches(':popover-open'))
  await page.mouse.move(800, 600)
  await page.waitForTimeout(180)
  assert.equal(await popup.evaluate(node => node.matches(':popover-open')), true, 'Native 350ms hover latch')
  await page.waitForFunction(() => !document.querySelector('.section-tab-reveal')?.matches(':popover-open'))
  for (const width of [360, 320]) {
    await page.setViewportSize({ width, height: 740 })
    await rows.first().getByRole('tab').tap()
    await ready()
    const beforeTouch = await order()
    const touch = await page.context().newCDPSession(page), bounds = await rows.nth(1).boundingBox()
    await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: bounds.x + 20, y: bounds.y + 21 }] })
    await page.waitForTimeout(560)
    await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await popup.getByRole('button', { name: 'Move section down', exact: true }).waitFor()
    assert((await popup.boundingBox()).x + (await popup.boundingBox()).width <= width)
    await popup.getByRole('button', { name: 'Move section down', exact: true }).tap()
    const afterTouch = [...beforeTouch]; afterTouch.splice(2, 0, afterTouch.splice(1, 1)[0])
    assert.deepEqual(await order(), afterTouch, 'Long press exposes touch reorder without hijacking scroll')
    assert.equal(await rail.locator('.dragging').count(), 0)
    await touch.detach()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  }
  assert.deepEqual(errors, [])
  console.log('PASS section tabs: native overlay/45px motion, mouse reorder, draft/order reload, cancellation, 350ms latch, touch long-press actions at 360/320')
} finally { await browser.close() }
