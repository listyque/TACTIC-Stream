import assert from 'node:assert/strict'

export async function exerciseSecurity(browser,url,catalog){
 const context=await browser.newContext({viewport:{width:1100,height:740},hasTouch:true})
 try{
  const page=await context.newPage(),errors=[],writes=[]
  page.on('pageerror',error=>errors.push(error.message))
  let stored=structuredClone(catalog),reads=0,reply='success'
  await page.route('**/admin/security-rules/*',async route=>{
   if(route.request().url().endsWith('/read')){reads++;await route.fulfill({json:{result:stored}});return}
   const payload=route.request().postDataJSON();writes.push(payload)
   if(reply==='unknown'){await route.abort('failed');return}
   if(reply==='conflict'){await route.fulfill({status:409,json:{error:'Access rules changed. Reload before saving.'}});return}
   stored={...stored,document:payload.document,revision:'saved-revision'}
   await route.fulfill({json:{result:stored}})
  })
  await page.goto(url)
  const control=id=>page.locator('[data-frame="'+id+'"]'),state=fn=>page.evaluate(fn)
  const ready=()=>page.waitForFunction(()=>window.frameAdmin.screen.value.document&&!window.frameAdmin.screen.value.busy)
  await ready()
  assert.equal(await control('adminSecurityCell_0_0').locator(':scope > .item-surface').evaluate(el=>getComputedStyle(el).borderRadius),'0px')
  assert.equal(await control('adminSecurityAccess_0_0').textContent(),'Allowed')
  await control('adminSecurityTab_defaults').tap()
  await control('adminSecurityInheritance_G1').tap()
  assert.equal(await state(()=>window.frameAdmin.screen.value.groupDocument.subGroups),'Artists 1')
  await state(()=>{window.frameAdmin.screen.value.document.groups.G2.subGroups='Artists 0'})
  assert(await control('adminSecurityInheritance_G2').isDisabled(),'a transitive cycle cannot be added')
  await state(()=>{window.frameAdmin.screen.value.document.groups.G2.subGroups=''})
  await control('adminSecurityInheritance_G1').tap()
  assert.equal(await state(()=>window.frameAdmin.screen.value.dirty),false,'removing inheritance restores the original draft')
  assert.equal(writes.length,0,'inheritance selection does not write without Save')
  await control('adminSecurityTab_project').tap()
  await control('adminSecurityCell_1_1').tap()
  await control('adminSecurityCell_1_1').locator('input').focus()
  await page.keyboard.press('ArrowDown')
  await page.waitForFunction(()=>document.activeElement?.closest('[data-frame]')?.dataset.frame==='adminSecurityCell_2_1')
  const grid=page.locator('.frame-grid-body')
  await grid.hover();await page.mouse.wheel(0,480);await page.waitForTimeout(180)
  assert(await grid.evaluate(el=>el.scrollTop>0),'real wheel scrolls the virtual matrix')
  await grid.evaluate(el=>{el.scrollTop=el.scrollLeft=0})
  assert.equal(writes.length,0,'matrix edits only change the draft')
  await control('adminSaveDocument').tap();assert.equal(writes.length,0,'save requires confirmation')
  await control('adminConfirmSave').tap();await ready()
  assert.equal(writes.length,1);assert.equal(writes[0].expected_revision,'fixture-revision')
  assert(writes[0].document.groups.G1.xml.includes('allow'))
  await control('adminSecurityTab_technical').tap()
  if(await control('adminSecurityTechnicalPages_xml').count())await control('adminSecurityTechnicalPages_xml').tap()
  else await control('adminSecurityTechnicalPages').selectOption('xml')
  const source=control('adminSecuritySource'),original=await source.inputValue()
  await source.fill('broken');await source.press('End');await source.press('x')
  assert.equal(await source.inputValue(),'brokenx','text remains editable after the first character')
  assert(await control('adminSaveDocument').isDisabled())
  assert(await control('adminSecurityTab_project').isDisabled(),'unapplied text locks navigation')
  await control('adminSecurityApplyText').tap()
  assert.equal(await source.inputValue(),'brokenx','parse failure preserves the text')
  assert.equal(writes.length,1)
  await control('adminReloadDocument').tap();await control('adminCancelSave').tap()
  assert.equal(reads,1);assert.equal(await source.inputValue(),'brokenx')
  await control('adminSecurityDiscardText').tap();assert.equal(await source.inputValue(),original)
  await source.fill('<rules><!--preserved--><rule category="studio_custom" key="frame" access="edit"/><extension name="kept"/></rules>')
  await control('adminSecurityApplyText').tap()
  assert.equal(writes.length,1,'applying XML is local')
  await control('adminSaveDocument').tap();await control('adminConfirmSave').tap();await ready()
  assert.equal(writes.length,2);assert.equal(writes.at(-1).expected_revision,'saved-revision')
  assert(writes.at(-1).document.groups.G0.xml.includes('<extension name="kept"'))
  await source.fill('<rules/>');await control('adminSecurityApplyText').tap()
  reply='unknown';await control('adminSaveDocument').tap();await control('adminConfirmSave').tap();await ready()
  assert(await control('adminSaveDocument').isDisabled())
  await state(()=>window.frameAdmin.screen.value.save());assert.equal(writes.length,3,'unknown write is not retried')
  assert.equal(await state(()=>window.frameAdmin.screen.value.canLeave()),false)
  await control('adminReloadDocument').tap();await control('adminCancelSave').tap();assert.equal(reads,1)
  await control('adminReloadDocument').tap();await control('adminConfirmSave').tap();await ready()
  assert.equal(reads,2);assert.equal(await state(()=>window.frameAdmin.screen.value.uncertain),false)
  await source.fill('<rules/>');await control('adminSecurityApplyText').tap()
  reply='conflict';await control('adminSaveDocument').tap();await control('adminConfirmSave').tap();await ready()
  assert.equal(await state(()=>window.frameAdmin.screen.value.uncertain),false)
  assert(await control('adminDocumentError').inputValue())
  await control('adminDiscardDocument').tap();await control('adminConfirmSave').tap()
  assert.equal(await source.inputValue(),stored.document.groups.G0.xml)
  await page.setViewportSize({width:360,height:740})
  await control('adminSecurityScope').selectOption('search_filter')
  await control('adminAddAccessRule').tap()
  await control('adminAccessField_value').fill('mobile')
  assert.equal(await state(()=>window.frameAdmin.screen.value.attributes.value),'mobile')
  assert.deepEqual(errors,[])
 }finally{await context.close()}
 console.log('Access rules real mouse/keyboard/touch, XML, draft/save/rollback, conflict and unknown-write guards passed')
}
