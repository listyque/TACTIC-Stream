import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1360, height: 900 }, hasTouch: true })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const editor = page.locator('.security-users'), admin = page.locator('.administration-dialog')
async function ready() { await page.waitForFunction(() => document.querySelector('.security-users')?.getAttribute('aria-busy') === 'false') }
async function save() {
  await admin.getByRole('button', { name: 'Save to server', exact: true }).tap()
  await editor.getByRole('button', { name: 'Confirm save', exact: true }).tap()
  await ready()
  assert.equal(await editor.getByRole('alert').count(), 0, await editor.getByRole('alert').allTextContents())
  assert.equal(await editor.locator('[data-frame="adminDocumentError"]').inputValue(), 'User saved on server')
}
try {
  await page.goto(process.argv[2] + '/projects/admin/?search_type=sthpw/project&view=table')
  await page.getByLabel('Login', { exact: true }).fill('admin')
  await page.getByLabel('Password', { exact: true }).fill('private-test-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).tap()
  await page.waitForFunction(() => document.querySelector('.workspace-results')?.getAttribute('aria-busy') === 'false')
  await page.getByLabel('More options', { exact: true }).tap()
  await page.locator('.settings-menu').getByRole('button', { name: 'Administration', exact: true }).tap()
  await page.waitForFunction(() => document.querySelector('.search-types-editor')?.getAttribute('aria-busy') === 'false')
  await admin.locator('.administration-navigation').getByRole('button', { name: 'Users', exact: true }).tap(); await ready()
  await admin.getByRole('button', { name: 'Create user', exact: true }).tap()
  await editor.getByLabel('Login', { exact: true }).fill('ui_user')
  await editor.getByLabel('First name', { exact: true }).fill('Test')
  await editor.getByLabel('Last name', { exact: true }).fill('Person')
  await editor.getByLabel('Display name', { exact: true }).fill('Test User')
  await editor.getByLabel('Email', { exact: true }).fill('test@example.test')
  await admin.locator('.administration-navigation').getByRole('button', { name: 'Groups', exact: true }).tap()
  await admin.locator('.administration-navigation').getByRole('button', { name: 'Users', exact: true }).tap()
  assert.equal(await editor.getByLabel('Display name', { exact: true }).inputValue(), 'Test User')
  await admin.getByRole('button', { name: 'Close administration', exact: true }).tap()
  assert.equal(await admin.isVisible(), true)
  await editor.getByRole('radio', { name: 'Account', exact: true }).tap()
  await editor.getByLabel('Password', { exact: true }).fill('browser-user-password')
  await editor.getByRole('button', { name: 'Edit group membership', exact: true }).tap()
  await editor.getByRole('checkbox', { name: 'ui_team', exact: true }).check()
  await save()
  await editor.getByRole('radio', { name: 'Account', exact: true }).tap()
  assert.equal(await editor.getByLabel('Password', { exact: true }).inputValue(), '')
  await editor.getByLabel('Hourly wage', { exact: true }).fill('12.5')
  await editor.getByRole('checkbox', { name: 'Retired', exact: true }).check()
  await save()
  assert.equal(await editor.locator('[data-frame="adminUsersList"]').getByRole('button', { name: 'Test User ui_user', exact: true }).count(), 0)
  await editor.getByRole('checkbox', { name: 'Show retired users', exact: true }).check()
  await editor.getByLabel('Name, login or email', { exact: true }).fill('example.test')
  const user = editor.locator('[data-frame="adminUsersList"]').getByRole('button', { name: 'Test User ui_user', exact: true })
  await user.waitFor(); await user.tap()
  assert.equal(await editor.getByLabel('Login', { exact: true }).getAttribute('readonly'), '')
  await editor.getByRole('radio', { name: 'Account', exact: true }).tap()
  assert.equal(await editor.getByLabel('Hourly wage', { exact: true }).inputValue(), '12.5')
  await editor.getByRole('checkbox', { name: 'Retired', exact: true }).uncheck(); await save()
  await admin.getByRole('button', { name: 'Reload from server', exact: true }).tap(); await ready()
  await editor.getByRole('radio', { name: 'Groups', exact: true }).tap()
  assert.equal(await editor.getByRole('checkbox', { name: 'ui_team', exact: true }).isChecked(), true)
  if (process.argv[3]) await page.screenshot({ path: process.argv[3], animations: 'disabled' })
  await page.setViewportSize({ width: 320, height: 740 })
  await editor.getByRole('radio', { name: 'Profile', exact: true }).tap()
  await editor.getByLabel('Display name', { exact: true }).fill('Unsaved')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.equal(await editor.locator('[data-frame="adminUserForm"]').evaluate(element => getComputedStyle(element).overflowY), 'auto')
  if (process.argv[3]) await page.screenshot({ path: process.argv[3].replace('.png', '-mobile.png'), animations: 'disabled' })
  await admin.getByRole('button', { name: 'Discard', exact: true }).tap()
  await editor.getByRole('button', { name: 'Discard changes', exact: true }).tap()
  assert.equal(await editor.getByLabel('Display name', { exact: true }).inputValue(), 'Test User')
  await admin.getByRole('button', { name: 'Close administration', exact: true }).tap()
  await admin.waitFor({ state: 'hidden' })
  assert.deepEqual(errors, [])
  console.log('Users: create/profile/password/group membership/retire/reactivate/search/reload/draft guards/mobile320 OK')
} finally { await browser.close() }
