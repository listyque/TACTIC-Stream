import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const base = process.argv[2], project = 'one'
const browser = await chromium.launch({headless:true})
try {
  const context = await browser.newContext({viewport:{width:1400,height:940},colorScheme:'dark'})
  const page = await context.newPage(), calls = [], errors = []
  page.setDefaultTimeout(15000)
  await page.addInitScript(() => {
    localStorage.setItem('tactic_stream.appearance','{"mode":"dark","language":"en"}')
    localStorage.setItem('tactic_stream.network','{"pollInterval":5,"updateMode":"poll"}')
  })
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/\/admin\/server-(updates|events)$/.test(request.url())) calls.push({url:request.url(),payload:request.postDataJSON()}) })
  await page.goto(base + '/projects/one/?search_type=sthpw/task&view=table')
  await page.getByLabel('Login',{exact:true}).fill('admin')
  await page.getByLabel('Password',{exact:true}).fill('private-test-password')
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await page.waitForFunction(() => document.querySelector('.workspace-results')?.getAttribute('aria-busy') === 'false')
  await page.evaluate(() => {
    window.app = document.querySelector('#app').__vue_app__._container._vnode.component.subTree.component.subTree.component.proxy
    window.batches = []
    window.app.$watch('serverBatch', value => { if (value) window.batches.push(value) })
  })
  const menu = page.locator('.connection-menu')
  await menu.getByLabel('Connection',{exact:true}).click()
  await menu.getByRole('menuitemradio',{name:'Server push (SSE)',exact:true}).click()
  await page.waitForFunction(() => window.batches.length > 0)
  const count = calls.length, batches = await page.evaluate(() => window.batches.length)
  await new Promise(resolve => setTimeout(resolve,2800))
  assert.equal(calls.length,count,'Idle SSE must not poll or reopen the stream')
  assert.equal(await page.evaluate(() => window.batches.length),batches,'Idle SSE must not emit empty data batches')
  assert(!calls.at(-1).url.includes(calls.at(-1).payload.ticket),'Ticket must stay out of the URL')
  const auth = {ticket:calls.at(-1).payload.ticket,project}
  async function rpc(method,...args) {
    const response = await page.request.post(base + '/admin/rpc',{data:{method,args}})
    const data = await response.json(); assert(response.ok(),JSON.stringify(data)); return data.result
  }
  const initialTasks = await rpc('query',auth,'sthpw/task')
  await rpc('update',auth,initialTasks[0].__search_key__,{description:'SSE_BROWSER_CHANGE'})
  await page.waitForFunction(() => window.batches.at(-1)?.cacheChanges?.some(row => row.searchType === 'sthpw/task'))

  // Script catalog events share the stream and preserve an unsaved editor buffer.
  await page.evaluate(() => window.app.openScriptEditor())
  const scriptEditor = page.locator('.script-editor-dialog')
  await page.waitForFunction(() => document.querySelector('.script-editor-dialog')?.getAttribute('aria-busy') === 'false')
  const scriptSource = scriptEditor.getByLabel('Script source', {exact:true})
  await scriptSource.fill('return "UNSAVED_SSE_BUFFER"')
  await rpc('insert', auth, 'config/custom_script', {folder:'sse_review',title:'live_catalog',language:'python',script:'return True'})
  await scriptEditor.getByText('live_catalog', {exact:true}).waitFor()
  assert.equal(await scriptSource.inputValue(), 'return "UNSAVED_SSE_BUFFER"')
  await scriptEditor.getByLabel('Close script editor', {exact:true}).click()

  const shelfRead = await page.request.post(base + '/admin/script-shelf/read', {data:auth})
  const shelfBefore = (await shelfRead.json()).result
  await page.evaluate(() => window.app.$refs.scriptShelf.open())
  const shelf = page.locator('.script-shelf-dialog')
  await page.waitForFunction(() => document.querySelector('.script-shelf-editor')?.getAttribute('aria-busy') === 'false')
  await shelf.getByRole('button', {name:'Add button',exact:true}).click()
  await shelf.getByLabel('Button label', {exact:true}).fill('LOCAL_SHELF_DRAFT')
  const remoteShelf = await page.request.post(base + '/admin/script-shelf/save', {data:{...auth,mode:'shared',title:'Remote shelf',revision:shelfBefore.revision,configuration:{scope:'global',entryKey:'',buttons:[]}}})
  assert(remoteShelf.ok(), JSON.stringify(await remoteShelf.json()))
  await page.waitForFunction(() => window.batches.at(-1)?.cacheChanges?.some(row => row.searchType === 'config/widget_config'))
  assert.equal(await shelf.getByLabel('Button label', {exact:true}).inputValue(), 'LOCAL_SHELF_DRAFT')
  const saveRequest = page.waitForRequest(request => request.url().endsWith('/admin/script-shelf/save'))
  await shelf.getByRole('button', {name:'Save shelf',exact:true}).click()
  assert.equal((await saveRequest).postDataJSON().revision, shelfBefore.revision, 'Remote updates must preserve the draft revision')
  await shelf.getByRole('button', {name:'Discard',exact:true}).click()
  await page.waitForFunction(() => document.querySelector('.script-shelf-editor')?.getAttribute('aria-busy') === 'false')
  await shelf.getByLabel('Close script shelf', {exact:true}).click()

  await menu.getByLabel('Connection',{exact:true}).click()
  await page.getByLabel('More options',{exact:true}).click()
  await page.locator('.settings-menu').getByRole('button',{name:'Configuration',exact:true}).click()
  const configuration = page.locator('.configuration-dialog:modal')
  await configuration.getByRole('navigation',{name:'Configuration sections'}).getByRole('button',{name:'Server',exact:true}).click()
  await page.waitForFunction(() => document.querySelector('.configuration-native')?.getAttribute('aria-busy') === 'false')
  assert.equal(await configuration.getByLabel('Update delivery',{exact:true}).inputValue(),'sse')
  assert.equal(await configuration.getByLabel('Server updates',{exact:true}).count(),0)
  assert.equal(await configuration.getByLabel('Update batching delay',{exact:true}).inputValue(), '200')
  await new Promise(resolve => setTimeout(resolve, 650))
  await configuration.getByRole('button', {name:'Refresh connections',exact:true}).click()
  await configuration.locator('.event-clients tbody tr').waitFor()
  assert.equal(await configuration.locator('.event-clients tbody tr').count(), 1)
  assert.match(await configuration.locator('.event-clients tbody tr').innerText(), /admin.*one.*Web browser/s)
  const worker = new AbortController()
  try {
    const stream = await fetch(base + '/admin/server-events', {method:'POST', headers:{'Content-Type':'application/json','X-Tactic-Client':'TACTIC Handler'},
      body:JSON.stringify({...auth,channels:['cache'],search_types:['sthpw/task']}), signal:worker.signal})
    assert.equal(stream.status, 200)
    await stream.body.getReader().read()
    const collector = configuration.locator('[id="services/update_interval"]')
    await collector.fill('0.8')
    await new Promise(resolve => setTimeout(resolve,650))
    await configuration.getByRole('button', {name:'Refresh connections',exact:true}).click()
    await page.waitForFunction(() => document.querySelectorAll('.event-clients tbody tr').length === 2)
    assert.equal(await collector.inputValue(), '0.8', 'Refreshing connections must keep the settings draft')
    assert.match(await configuration.locator('.event-clients tbody').innerText(), /TACTIC Handler/)
    worker.abort()
    await new Promise(resolve => setTimeout(resolve,650))
    await configuration.getByRole('button', {name:'Refresh connections',exact:true}).click()
    await page.waitForFunction(() => document.querySelectorAll('.event-clients tbody tr').length === 1)
    await configuration.locator('.configuration-header').getByRole('button', {name:'Reset',exact:true}).click()
    assert.equal(await collector.inputValue(), '')
    await configuration.getByLabel('Update batching delay',{exact:true}).selectOption('1000')
    await configuration.locator('.configuration-header').getByRole('button', {name:'Apply',exact:true}).click()
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('tactic_stream.network')).batchDelay === 1000)
  } finally { worker.abort() }
  while (await page.getByRole('button', {name:'Dismiss notification',exact:true}).count()) {
    await page.getByRole('button', {name:'Dismiss notification',exact:true}).first().click()
  }
  await configuration.locator('.configuration-pages').evaluate(element => { element.scrollTop = 0 })
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({path:'../.screenshots/sse-configuration.png',animations:'disabled'})
  await configuration.locator('.configuration-header').getByRole('button',{name:'Close',exact:true}).click()
  await configuration.waitFor({state:'hidden'})

  // A native task change refreshes the manager without a timer or overwriting its draft.
  await page.getByLabel('More options',{exact:true}).click()
  await page.getByRole('button',{name:'Task Manager',exact:true}).click()
  const manager = page.getByRole('dialog',{name:'Task Manager',exact:true})
  const ready = () => page.waitForFunction(() => document.querySelector('.task-manager-results')?.getAttribute('aria-busy') === 'false')
  await ready()
  await manager.locator('.task-manager-scope > summary').click()
  await manager.getByLabel('Task scope',{exact:true}).selectOption('project'); await ready()
  await manager.locator('.task-manager-scope > summary').click()
  const row = manager.locator('tr[data-task-key]').first(), key = await row.getAttribute('data-task-key')
  await row.getByRole('checkbox').check()
  await manager.getByRole('button',{name:'Edit selected tasks',exact:true}).click()
  const editor = page.getByRole('dialog',{name:'Edit task draft',exact:true})
  await editor.locator('[data-task-field="description"] textarea').fill('SSE_UNSAVED_DRAFT')
  await editor.getByRole('button',{name:'Apply to draft',exact:true}).click()
  await rpc('update',auth,key,{description:'SSE_PARALLEL_TASK'})
  await manager.getByText('Tasks changed on the server. Refresh to review current values; your draft keeps its original revisions.').waitFor()
  const beforeReconnect = await page.evaluate(() => window.batches.length)
  await context.setOffline(true)
  await page.waitForFunction(() => window.app.connectionOnline === false)
  await new Promise(resolve => setTimeout(resolve,500))
  await context.setOffline(false)
  await page.waitForFunction(count => window.batches.length > count && window.batches.at(-1).reconnected, beforeReconnect)
  await manager.getByRole('button',{name:'Edit selected tasks',exact:true}).click()
  assert.equal(await editor.locator('[data-task-field="description"] textarea').inputValue(),'SSE_UNSAVED_DRAFT')
  await editor.getByRole('button',{name:'Cancel',exact:true}).click()
  await manager.getByRole('button',{name:'Discard task changes',exact:true}).click()
  await page.getByRole('button',{name:'Close panel: Task Manager',exact:true}).click()

  await menu.getByLabel('Connection',{exact:true}).click()
  const poll = page.waitForResponse(response => response.url().endsWith('/admin/server-updates'))
  await menu.getByRole('menuitemradio',{name:'Periodic checks',exact:true}).click(); await poll
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('tactic_stream.network')).updateMode),'poll')
  await page.route('**/admin/server-events', route => route.fulfill({status:403,json:{error:'Session ended.',error_code:'authentication_failed'}}))
  await menu.getByLabel('Connection',{exact:true}).click()
  await menu.getByRole('menuitemradio',{name:'Server push (SSE)',exact:true}).click()
  await page.getByLabel('Password',{exact:true}).waitFor()
  assert.deepEqual(errors,[])
  console.log('PASS: optional SSE, real connection list/disconnect/draft preservation, batching settings, idle silence, native updates, Configuration, task drafts, offline recovery, poll switch and expired session')
} finally { await browser.close() }
