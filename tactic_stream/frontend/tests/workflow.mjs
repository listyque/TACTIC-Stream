  await editor.getByLabel('Default duration, days', { exact: true }).press('Tab')
  await editor.getByLabel('Horizontal position', { exact: true }).fill('70')
  await editor.getByLabel('Horizontal position', { exact: true }).press('Tab')
  await editor.getByLabel('Process name', { exact: true }).fill('finish')
  await editor.locator('.workflow-tools').getByLabel('Node type', { exact: true }).selectOption('action')
  await editor.locator('.workflow-tools').getByRole('button', { name: 'Add process', exact: true }).tap()
  await editor.getByLabel('Script body', { exact: true }).fill('return True')
  await editor.getByLabel('Source', { exact: true }).first().selectOption('work')
  await editor.getByLabel('Destination', { exact: true }).first().selectOption('finish')
  await editor.getByRole('button', { name: 'Connect', exact: true }).tap()
  assert.equal(await editor.locator('.relationship-node').count(), 2)
  assert.equal(await editor.locator('.relationship-edge').count(), 1)
  await editor.getByRole('button', { name: 'Save workflow', exact: true }).tap()
  await ready()
  assert.equal(await editor.getByRole('alert').count(), 0)
  assert.equal(await editor.getByRole('button', { name: 'Save workflow', exact: true }).isDisabled(), true)
  await editor.locator('.relationship-node[data-identity="work"]').tap()
  assert.equal(await editor.getByLabel('Default duration, days', { exact: true }).inputValue(), '3')
  await editor.getByRole('button', { name: 'Open process dependencies', exact: true }).tap()
  const rules = page.getByRole('dialog', { name: 'Process dependencies', exact: true })
  const rulesReady = () => page.waitForFunction(() => document.querySelector('.process-rules-editor[open]')?.getAttribute('aria-busy') === 'false')
