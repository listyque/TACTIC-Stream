  await rules.getByLabel('Actual date', { exact: true }).selectOption('actual_start_date')
  page.once('dialog', dialog => dialog.accept())
  await rules.getByRole('button', { name: 'Save rules', exact: true }).tap()
  await rulesReady()
  assert.equal(await rules.getByRole('alert').count(), 0)
  await rules.getByRole('button', { name: 'Close process dependencies', exact: true }).tap()
  await editor.locator('.relationship-node[data-identity="finish"]').tap()
  await editor.locator('.workflow-document').evaluate(node => node.scrollTop = 0)
  if (process.argv[3]) await page.screenshot({ path: process.argv[3].replace('-mobile.png', '-desktop.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 320, height: 740 })
  await editor.locator('.relationship-node[data-identity="finish"]').tap()
  await editor.getByLabel('Script body', { exact: true }).fill('return 42')
