  await types.locator('[data-metric="total"]').waitFor()
  await types.getByRole('button', { name: 'contract/entity', exact: true }).tap()
  await types.getByRole('tab', { name: 'Workflow', exact: true }).tap()
  await types.getByRole('button', { name: 'Create workflow', exact: true }).tap()
  const editor = page.getByRole('dialog', { name: 'Workflow editor', exact: true })
  const ready = () => page.waitForFunction(() => document.querySelector('dialog.workflow-editor[open]')?.getAttribute('aria-busy') === 'false')
  await ready()
  await editor.getByRole('button', { name: 'Details', exact: true }).tap()
  await editor.getByLabel('Title', { exact: true }).fill('Browser workflow')
  await editor.getByRole('radio', { name: 'Canvas', exact: true }).tap()
  await editor.locator('.workflow-tools > summary').tap()
  await editor.getByLabel('Process name', { exact: true }).fill('work')
  await editor.locator('.workflow-tools').getByRole('button', { name: 'Add process', exact: true }).tap()
