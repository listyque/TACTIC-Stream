import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { selectProject } from './project_selection.mjs'

const base = process.argv[2], project = process.env.STREAM_CHECK_PROJECT
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 740 }, colorScheme: 'dark' })
  page.setDefaultTimeout(12000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode: 'dark', language: 'en' })))
  const ready = () => page.waitForFunction(() => document.querySelector('.workspace-results')?.getAttribute('aria-busy') === 'false')
  await page.goto(base + '/')
  await page.getByLabel('Login', { exact: true }).fill(process.env.STREAM_CHECK_LOGIN || 'admin')
  await page.getByLabel('Password', { exact: true }).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await selectProject(page, project)
  await page.goto(base + '/projects/' + encodeURIComponent(project) + '/?' + new URLSearchParams({ search_type: 'sthpw/search_object', view: 'table' }))
  await ready()
  const footer = page.locator('.workspace-footer'), viewport = page.locator('.workspace-results')
  const rows = viewport.locator('.configured-view:visible tbody tr')
  await footer.getByLabel('Items per page', { exact: true }).click()
  await footer.getByRole('button', { name: '20 items', exact: true }).click()
  await ready()
  await footer.getByLabel('Next →', { exact: true }).click()
  await ready()
  assert.match(await footer.locator('.result-range').innerText(), /^21–/)
  await rows.first().getByRole('checkbox').check()
  const texts = await rows.allInnerTexts()
  await viewport.evaluate(node => node.scrollTop = 200)
  const scroll = await viewport.evaluate(node => node.scrollTop)
  assert(scroll > 0)
  await page.getByLabel('More options', { exact: true }).click()
  await page.locator('.settings-menu').getByRole('button', { name: 'Save Preferences', exact: true }).click()
  const saved = await page.evaluate(project => {
    const workspace = JSON.parse(localStorage.getItem('tactic_stream.workspace.admin'))[project]
    const section = workspace.sections.find(section => section.id === workspace.current)
    return { section: section.id, tab: section.current, keys: section.tabs.find(tab => tab.id === section.current).state.selectedKeys }
  }, project)
  await page.addInitScript(project => {
    const key = 'tactic_stream.workspace.admin', saved = JSON.parse(localStorage.getItem(key))
    const workspace = saved[project], section = workspace.sections.find(section => section.id === workspace.current)
    section.tabs.find(tab => tab.id === section.current).state.selectedKeys.push('sthpw/search_object?code=NO_LONGER_AVAILABLE')
    localStorage.setItem(key, JSON.stringify(saved))
  }, project)
  await page.reload()
  await ready()
  assert.match(await footer.locator('.result-range').innerText(), /^21–/, 'Reload preserves the second result page')
  assert.deepEqual(await rows.allInnerTexts(), texts)
  assert.equal(await rows.first().getByRole('checkbox').isChecked(), true, 'Reload preserves selection of server-returned objects')
  assert.equal(await viewport.evaluate(node => node.scrollTop), scroll)
  assert.equal(await page.locator('.section-tab-row:has([aria-selected="true"])').getAttribute('data-section-id'), saved.section)
  assert.equal(await page.locator('.workspace-tabs[data-kind="search"] [aria-selected="true"]').getAttribute('data-tab-id'), saved.tab)
  assert.equal(new URL(page.url()).pathname, '/projects/' + encodeURIComponent(project) + '/')
  assert.deepEqual(await page.evaluate(project => {
    const workspace = JSON.parse(localStorage.getItem('tactic_stream.workspace.admin'))[project]
    const section = workspace.sections.find(section => section.id === workspace.current)
    return section.tabs.find(tab => tab.id === section.current).state.selectedKeys
  }, project), saved.keys, 'Unavailable saved keys are pruned against the current server response')
  await selectProject(page, 'admin')
  await ready()
  await selectProject(page, project)
  await ready()
  assert.match(await footer.locator('.result-range').innerText(), /^21–/)
  assert.equal(await rows.first().getByRole('checkbox').isChecked(), true, 'Project switching retains its own selected objects')
  assert.equal(await viewport.evaluate(node => node.scrollTop), scroll)
  await page.setViewportSize({ width: 320, height: 740 })
  await page.reload()
  await ready()
  assert.match(await footer.locator('.result-range').innerText(), /^21–/)
  assert.equal(await rows.first().getByRole('checkbox').isChecked(), true)
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.screenshot({ path: '../.screenshots/handler-current/stream-workspace-restored-320.png', animations: 'disabled' })
  await page.setViewportSize({ width: 1280, height: 740 })
  await page.getByLabel('More options', { exact: true }).click()
  await page.locator('.settings-menu').getByRole('button', { name: 'Task Manager', exact: true }).click()
  const task = page.locator('[data-dock="tasks"]')
  await task.locator('.task-manager-results[aria-busy="false"]').waitFor()
  await task.getByLabel('Panel position: Task Manager', { exact: true }).click()
  await task.getByRole('button', { name: 'Dock bottom', exact: true }).click()
  const divider = page.getByRole('separator', { name: 'Resize workspace panels', exact: true })
  assert.equal(await divider.getAttribute('aria-orientation'), 'horizontal')
  const targetUrl = page.url()
  await page.getByLabel('More options', { exact: true }).click()
  await page.locator('.settings-menu').getByRole('button', { name: 'Save Preferences', exact: true }).click()
  await selectProject(page, 'admin')
  await ready()
  await task.waitFor({ state: 'hidden' })
  await page.goto(targetUrl)
  await ready()
  await task.locator('.task-manager-results[aria-busy="false"]').waitFor()
  assert.equal(await divider.getAttribute('aria-orientation'), 'horizontal', 'The target tab restores its dock arrangement, overriding the last global layout')
  assert.equal(await task.locator('.error').count(), 0)
  assert.match(await footer.locator('.result-range').innerText(), /^21–/)
  assert.equal(await rows.first().getByRole('checkbox').isChecked(), true)
  await page.screenshot({ path: '../.screenshots/handler-current/stream-workspace-restored-dock.png', animations: 'disabled' })
  assert.deepEqual(errors, [])
  console.log('PASS workspace restore: project/tab identity, second page, server-backed selection, scroll, project isolation, 320px reload and working dock arrangement')
} finally { await browser.close() }
