import { closeInspector } from './inspector_helpers.mjs'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'
import { selectProject } from './project_selection.mjs'

const output = '../.screenshots/continuous-current'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1454, height: 1000 } })
page.setDefaultTimeout(10000)
const project = process.env.STREAM_CHECK_PROJECT || 'cg_test'
const errors = []
page.on('pageerror', error => errors.push(error.message))
const surface = page.locator('.workspace-browser .result-presentation:visible')
const episode = surface.locator('article[data-result-key*="code=DEMO_EP01"]').first()
const branch = title => surface.locator('.result-item-branch').filter({ has: page.locator('strong', { hasText: new RegExp('^' + title + '$') }) })
const capture = async name => {
  await page.waitForTimeout(560)
  await surface.screenshot({ path: output + '/web-' + name + '.png' })
}
try {
  await page.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode: 'dark', language: 'en' })))
  await page.goto(process.argv[2] + '/projects/' + project + '/?search_type=cg%2Fscenes&view=table')
  await page.getByLabel('Login', { exact: true }).fill('admin')
  await page.getByLabel('Password', { exact: true }).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await selectProject(page, project)
  await page.goto(process.argv[2] + '/projects/' + project + '/?search_type=cg%2Fscenes&view=table')
  await page.getByLabel('Change search results view', { exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'Continuous tree', exact: true }).click()
  await episode.waitFor()
  await episode.getByRole('button', { name: 'Expand item', exact: true }).click()
  await branch('Assets').waitFor()
  await page.mouse.move(0, 0)
  await capture('normal')
  await episode.hover({ position: { x: 700, y: 50 } })
  await capture('object-hover')
  await episode.locator('strong').hover()
  await capture('title-hover')
  const assets = branch('Assets').first()
  await assets.hover({ position: { x: 700, y: 19 } })
  await capture('relation-hover')
  await assets.locator('strong').click()
  assert.equal(await assets.getByRole('button', { name: 'Collapse item', exact: true }).count(), 0,
    'Handler single click selects a branch; only disclosure/double click expands it')
  await capture('relation-selected')
  await assets.locator('strong').dblclick()
  await assets.getByRole('button', { name: 'Collapse item', exact: true }).waitFor()
  await surface.locator('article[data-node-id*="/relation:cg/assets:"][data-result-key*="code=DEMO_ROBOT"]').waitFor()
  await assets.getByRole('button', { name: 'Collapse item', exact: true }).click()
  await assets.hover({ position: { x: 700, y: 19 } })
  assert.equal(await assets.getByRole('button', { name: 'Object actions', exact: true }).count(), 0)
  await episode.locator('strong').hover()
  await episode.getByRole('button', { name: 'Save snapshot', exact: true }).click()
  const checkin = page.getByRole('dialog', { name: 'Save snapshot', exact: true })
  await checkin.waitFor()
  await checkin.getByRole('button', { name: 'Close', exact: true }).click()
  await episode.hover({ position: { x: 700, y: 50 } })
  await episode.getByLabel('Related and child objects', { exact: true }).click()
  await page.getByRole('menuitem', { name: 'Assets', exact: true }).click()
  const related = page.getByRole('dialog', { name: 'Related objects', exact: true })
  await related.waitFor()
  await related.getByRole('button', { name: 'Close related objects', exact: true }).click()
  await episode.getByRole('button', { name: 'Tasks', exact: true }).click()
  // Aggregate buttons must offer the process instead of silently choosing the first task.
  await page.getByRole('menuitem', { name: /Сценарий/ }).waitFor()
  await page.keyboard.press('Escape')
  const processRow = branch('Сториборд')
  await page.evaluate(() => document.activeElement?.blur())
  await processRow.hover({ position: { x: 700, y: 16 } })
  await capture('process-hover')
  await page.mouse.down()
  await capture('process-pressed')
  await page.mouse.up()
  await page.mouse.move(0, 0)
  await capture('process-selected')
  await processRow.hover({ position: { x: 700, y: 16 } })
  const note = processRow.getByRole('button', { name: 'Notes', exact: true })
  const glyph = await note.locator('.icon-glyph').boundingBox()
  await page.mouse.click(glyph.x + glyph.width / 2, glyph.y + glyph.height / 2)
  await page.getByRole('region', { name: 'Task Inspector', exact: true }).waitFor()
  await closeInspector(page)
  await assets.focus()
  await assets.press('ArrowRight')
  await assets.getByRole('button', { name: 'Collapse item', exact: true }).waitFor()
  await assets.press('ArrowLeft')
  await assets.getByRole('button', { name: 'Expand item', exact: true }).waitFor()
  await assets.getByRole('button', { name: 'Create related object', exact: true }).click()
  await page.getByRole('dialog', { name: 'Record form', exact: true }).getByLabel('Name', { exact: true }).waitFor()
  await page.getByRole('dialog', { name: 'Record form', exact: true }).getByRole('button', { name: 'Close', exact: true }).click()
  await episode.locator('strong').click({ button: 'right' })
  await page.getByRole('button', { name: 'Advanced menu', exact: true }).click()
  await page.getByRole('button', { name: 'Copy Search Key', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  const secondEpisode = surface.locator('article[data-result-key*="code=DEMO_EP02"]').first()
  await episode.locator('strong').click()
  await secondEpisode.locator('strong').click({ modifiers: ['Control'] })
  assert.equal(await surface.locator('.result-item.selected:not(.result-item-branch)').count(), 2)
  await secondEpisode.locator('strong').click({ button: 'right' })
  assert.equal(await surface.locator('.result-item.selected:not(.result-item-branch)').count(), 2, 'Context menu preserves multi-selection')
  await page.keyboard.press('Escape')
  await episode.locator('strong').click()
  await secondEpisode.locator('strong').click({ modifiers: ['Shift'] })
  assert.equal(await surface.locator('.result-item.selected:not(.result-item-branch)').count(), 2)
  await episode.locator('strong').click()
  await assets.getByRole('button', { name: 'Expand item', exact: true }).click()
  const robot = surface.locator('article[data-node-id*="/relation:cg/assets:"][data-result-key*="code=DEMO_ROBOT"]').first()
  await robot.getByRole('button', { name: 'Expand item', exact: true }).click()
  await robot.getByRole('button', { name: 'Tasks', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Choose task', exact: true }).click()
  await page.getByRole('menuitem', { name: 'publish/look', exact: true }).click()
  const inspector = page.getByRole('region', { name: 'Task Inspector', exact: true })
  await inspector.waitFor()
  await closeInspector(page)
  const robotId = await robot.getAttribute('data-node-id')
  const publish = surface.locator('article[data-node-id="' + robotId + '/process:publish"]')
  await publish.getByRole('button', { name: 'Expand item', exact: true }).click()
  const latest = surface.locator('article[data-node-id^="' + robotId + '/process:publish/"]').filter({ has: page.locator('.result-snapshot-version', { hasText: /^latest$/ }) }).filter({ has: page.locator('.result-snapshot-description small', { hasText: /^publish$/ }) }).first()
  await latest.waitFor()
  await latest.getByRole('button', { name: 'Expand item', exact: true }).click()
  const latestId = await latest.getAttribute('data-node-id')
  const versions = surface.locator('article[data-node-id^="' + latestId + '/"]')
  await versions.locator('.result-snapshot-version').first().waitFor()
  assert.equal(await versions.locator('.result-snapshot-version').count(), 3)
  assert.deepEqual(await versions.locator('.result-snapshot-version').allTextContents(), ['v003', 'v002', 'v001'])
  assert.equal(await versions.filter({ has: page.locator('strong', { hasText: /^Versions$/ }) }).count(), 0)
  await latest.locator('.result-preview').click()
  assert.ok(await latest.evaluate(el => el.classList.contains('selected')), 'Preview selects the snapshot instead of opening a dialog')
  assert.equal(await page.getByRole('dialog', { name: 'File preview', exact: true }).count(), 0)
  await latest.locator('strong').hover()
  await latest.getByRole('button', { name: 'Save snapshot', exact: true }).click()
  await checkin.waitFor()
  await checkin.getByRole('button', { name: 'Close', exact: true }).click()
  await latest.locator('strong').hover()
  await latest.getByRole('button', { name: 'Open snapshot', exact: true }).click()
  const preview = page.getByRole('dialog', { name: 'File preview', exact: true })
  await preview.waitFor()
  await preview.getByRole('button', { name: 'Close preview', exact: true }).click()
  await latest.locator('strong').dblclick()
  await preview.waitFor()
  await preview.getByRole('button', { name: 'Close preview', exact: true }).click()
  await assets.getByRole('button', { name: 'Collapse item', exact: true }).click({ modifiers: ['Shift'] })
  await assets.getByRole('button', { name: 'Expand item', exact: true }).click()
  assert.equal(await robot.getByRole('button', { name: 'Collapse item', exact: true }).count(), 0, 'Recursive collapse also closes descendants')
  await assets.getByRole('button', { name: 'Collapse item', exact: true }).click()
  const shotBranch = branch('Shot').first()
  await shotBranch.getByRole('button', { name: 'Expand item', exact: true }).click()
  const shot = surface.locator('article[data-result-key*="code=DEMO_SH010"]').first()
  await shot.hover({ position: { x: 700, y: 50 } })
  await shot.getByRole('button', { name: 'Related and child objects', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Episode', exact: true }).click()
  await related.waitFor()
  await related.getByText('Episode 01 — Arrival', { exact: true }).waitFor()
  await related.getByRole('button', { name: 'Close related objects', exact: true }).click()
  assert.deepEqual(errors, [])
  console.log('PASS: tree hover/actions, single/double click, glyph clicks, process/task picker, check-in, related objects, keyboard/recursive disclosure, direct version children and Ctrl/Shift selection')
} catch (error) {
  await page.screenshot({ path: output + '/failure.png' })
  throw error
} finally {
  await browser.close()
}
