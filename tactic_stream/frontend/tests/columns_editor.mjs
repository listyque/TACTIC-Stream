  await admin.getByRole('button', { name: 'Close administration', exact: true }).tap(); await admin.waitFor({ state: 'hidden' })
  assert.deepEqual(errors, [])
  console.log('Columns Editor: catalog/wizard/XML/custom options/visibility/width/native save/workspace refresh/input definitions/filter/mobile320/draft guard OK')
