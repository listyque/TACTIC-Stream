import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const [base, output] = process.argv.slice(2);
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode: 'dark', language: 'en' })));
  await page.goto(base + '/projects/one/');
  await page.getByLabel('Login', { exact: true }).fill('admin');
  await page.getByLabel('Password', { exact: true }).fill(process.env.STREAM_CHECK_PASSWORD);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  async function open() {
    await page.getByLabel('More options', { exact: true }).click();
    await page.locator('.settings-menu').getByRole('button', { name: 'External agent', exact: true }).click();
  }
  await open();
  const chat = page.locator('.agent-request-dialog');
  const history = chat.locator('[data-frame=agentChatHistory]');
  const main = chat.locator('[data-frame=agentChatMain]');
  await history.getByRole('button', { name: 'Previous delivery', exact: true }).waitFor();
  const firstRow = history.locator('[data-frame-row]').filter({ has: page.getByRole('button', { name: 'Previous delivery', exact: true }) });
  const rowMenu = firstRow.locator('.frame-secondary-action');
  await page.mouse.move(0, 0);
  assert.equal(await rowMenu.evaluate(node => getComputedStyle(node).opacity), '0');
  await firstRow.hover();
  assert.equal(await rowMenu.evaluate(node => getComputedStyle(node).opacity), '1');
  await firstRow.getByRole('button', { name: 'Previous delivery', exact: true }).focus();
  await page.mouse.move(0, 0);
  assert.equal(await rowMenu.evaluate(node => getComputedStyle(node).opacity), '1');
  await main.getByRole('button', { name: 'New conversation', exact: true }).focus();
  await chat.evaluate(element => { element.style.width = '1202px';element.style.height = '802px'; });
  await page.evaluate(() => document.fonts.ready);
  await chat.locator('.agent-request-body').screenshot({ path: output + '/web-history-initial.png' });
  await history.getByRole('button', { name: 'New conversation', exact: true }).click();
  await main.getByRole('button', { name: 'Conversation settings', exact: true }).click();
  await history.getByRole('textbox', { name: 'Conversation name', exact: true }).fill('Named review');
  await history.getByRole('button', { name: 'Save', exact: true }).click();
  await main.locator('[data-frame=agentRequestTitle]').getByText('Named review', { exact: true }).waitFor();
  await history.getByRole('button', { name: 'Conversation view', exact: true }).click();
  await history.getByRole('button', { name: 'New conversation folder', exact: true }).click();
  await history.getByRole('textbox', { name: 'Folder name', exact: true }).fill('Production');
  await history.getByRole('button', { name: 'Save', exact: true }).click();
  await history.getByRole('button', { name: 'Named review', exact: true }).waitFor();
  await main.getByRole('button', { name: 'Conversation settings', exact: true }).click();
  const folders = history.getByRole('combobox', { name: 'Conversation folder', exact: true });
  const folder = await folders.locator('option').filter({ hasText: 'Production' }).getAttribute('value');
  await folders.selectOption(folder);
  await history.getByRole('switch', { name: 'Pin conversation', exact: true }).check();
  await history.getByRole('button', { name: 'Save', exact: true }).click();
  await history.getByRole('button', { name: 'Named review', exact: true }).waitFor();
  await history.getByRole('button', { name: 'Conversation view', exact: true }).click();
  await history.getByRole('combobox', { name: 'Group conversations', exact: true }).selectOption('group');
  await history.getByRole('button', { name: 'Production', exact: true }).waitFor();
  await chat.locator('.agent-request-body').screenshot({ path: output + '/web-history-folders.png' });
  await main.getByLabel('What should the agent do?', { exact: true }).fill('Unsent browser message');
  await history.getByRole('button', { name: 'New conversation', exact: true }).click();
  await history.getByRole('button', { name: 'Named review', exact: true }).click();
  assert.equal(await main.getByLabel('What should the agent do?', { exact: true }).inputValue(), 'Unsent browser message');
  await main.getByRole('button', { name: 'Conversation settings', exact: true }).click();
  await history.getByRole('button', { name: 'Archive conversation', exact: true }).click();
  await main.getByText('Archived conversation — restore it to continue', { exact: true }).waitFor();
  await history.getByRole('button', { name: 'Conversation view', exact: true }).click();
  await history.getByRole('switch', { name: 'Archived conversations', exact: true }).click();
  await history.getByRole('button', { name: 'Named review', exact: true }).waitFor();
  await main.getByRole('button', { name: 'Conversation settings', exact: true }).click();
  await history.getByRole('button', { name: 'Restore conversation', exact: true }).click();
  await history.getByRole('button', { name: 'Conversation view', exact: true }).click();
  await history.getByRole('switch', { name: 'Archived conversations', exact: true }).click();
  await history.getByRole('button', { name: 'Conversation view', exact: true }).click();
  await history.getByRole('combobox', { name: 'Group conversations', exact: true }).selectOption('type');
  await history.locator('[data-frame-row="type:cg/shot"]').waitFor();
  await history.getByRole('button', { name: 'Search conversations', exact: true }).click();
  await history.getByRole('textbox', { name: 'Search conversations', exact: true }).fill('Named review');
  await page.waitForFunction(() => document.querySelectorAll('[data-frame=agentHistoryList] .frame-action[data-frame^=agentHistoryOpen_]').length === 1);
  await history.getByRole('button', { name: 'Named review', exact: true }).waitFor();
  await page.setViewportSize({ width: 560, height: 900 });
  await main.getByRole('button', { name: 'Show conversations', exact: true }).click();
  await history.getByRole('button', { name: 'Named review', exact: true }).waitFor();
  await chat.locator('.agent-request-body').screenshot({ path: output + '/web-history-narrow.png' });
  await history.getByRole('button', { name: 'Named review', exact: true }).click();
  await main.getByLabel('What should the agent do?', { exact: true }).waitFor();
  await page.reload();
  await open();
  await chat.getByRole('button', { name: 'Show conversations', exact: true }).click();
  await history.getByRole('button', { name: 'Named review', exact: true }).waitFor();
  assert.deepEqual(errors, []);
  const touchContext = await browser.newContext({ storageState: await page.context().storageState(), hasTouch: true, isMobile: true, viewport: { width: 520, height: 900 } });
  const touch = await touchContext.newPage();
  await touch.goto(base + '/projects/one/');
  await touch.getByLabel('More options', { exact: true }).tap();
  await touch.locator('.settings-menu').getByRole('button', { name: 'External agent', exact: true }).tap();
  const touchChat = touch.locator('.agent-request-dialog');
  await touchChat.getByRole('button', { name: 'Show conversations', exact: true }).tap();
  const touchMenu = touchChat.locator('.frame-action[data-frame^=agentHistoryEdit_]').first();
  await touchMenu.waitFor();
  assert.equal(await touch.evaluate(() => matchMedia('(hover: none)').matches), true);
  assert.equal(await touchMenu.evaluate(node => getComputedStyle(node).opacity), '1');
  await touchMenu.tap();
  await touchChat.getByRole('textbox', { name: 'Conversation name', exact: true }).waitFor();
  await touchContext.close();
  console.log('Real web sidebar: named drafts, folders, pin, archive/restore, search, type grouping, draft switching, responsive panel and reload persistence passed');
} finally { await browser.close(); }
