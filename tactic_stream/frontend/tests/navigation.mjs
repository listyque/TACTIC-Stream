import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { selectProject } from './project_selection.mjs'

const browser = await chromium.launch({ headless:true })
try {
  const page = await browser.newPage({ viewport:{ width:1280, height:900 }, hasTouch:true })
  page.setDefaultTimeout(10000)
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error' && message.text().includes('Cannot read properties')) errors.push(message.text()) })
  await page.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode:'dark', language:'en' })))
  await page.goto(process.argv[2] + '/')
  await page.getByLabel('Login', { exact: true }).fill('admin')
  await page.getByLabel('Password', { exact:true }).fill('private-test-password')
  await page.getByRole('button', { name:'Sign in', exact:true }).click()
  await page.locator('.workspace-empty').waitFor()
  await selectProject(page, 'one')
  const tabs = page.locator('.workspace-rail [role="tab"]')
  while (await tabs.count()) await tabs.first().press('Delete')
  await page.getByRole('heading', { name:'No Search Type open', exact:true }).waitFor()
  const open = page.locator('.workspace-empty').getByRole('button', { name:'Open navigation', exact:true })
  const drawer = page.locator('#workspace-sidebar')
  const origin = await open.boundingBox(), x = origin.x + origin.width / 2, y = origin.y + origin.height / 2
  await open.click()
  await drawer.waitFor({ state:'visible' })
  await page.mouse.move(x + 12, y + 8)
  assert.equal(await drawer.evaluate(node => node.open), true, 'Moving from the central opener must not dismiss navigation')
  await page.mouse.move(180, y, { steps:10 })
  assert.equal(await drawer.evaluate(node => node.open), true, 'The drawer stays open while approaching its items')
  await page.screenshot({ path:'../.screenshots/navigation-from-empty.png', animations:'disabled' })
  const bounds = await drawer.boundingBox()
  await page.mouse.move(bounds.x + bounds.width + 60, y)
  assert.equal(await drawer.evaluate(node => node.open), true, 'The Handler 120px exit margin is preserved')
  await page.mouse.move(bounds.x + bounds.width + 160, y)
  await drawer.waitFor({ state:'hidden' })
  await open.click()
  await page.mouse.move(x + 15, y + 10)
  assert.equal(await drawer.evaluate(node => node.open), true, 'Each opening starts with auto-close unarmed')
  await page.mouse.click(x + 30, y + 30)
  await drawer.waitFor({ state:'hidden' })
  await open.press('Enter')
  await drawer.waitFor({ state:'visible' })
  await page.keyboard.press('Escape')
  await drawer.waitFor({ state:'hidden' })
  await page.setViewportSize({ width:320, height:760 })
  await open.tap()
  await drawer.waitFor({ state:'visible' })
  await drawer.getByRole('button', { name:'Close navigation', exact:true }).tap()
  await drawer.waitFor({ state:'hidden' })
  await open.tap()
  await drawer.locator('[data-search-type="contract/entity"]').first().tap()
  await drawer.waitFor({ state:'hidden' })
  await page.waitForFunction(() => document.querySelector('.workspace-results')?.getAttribute('aria-busy') === 'false')
  assert.equal(await page.locator('.workspace-empty').count(), 0, 'Choosing a Search Type leaves the empty screen')
  const view = page.locator('.workspace-browser .configured-view:visible').first()
  assert.equal(await view.getAttribute('data-result-mode'), 'continious', 'New Search Types default to the continuous tree')
  await page.setViewportSize({ width:1280, height:900 })
  await page.getByLabel('Change search results view', { exact:true }).click()
  await page.getByRole('menuitemradio', { name:'Table', exact:true }).click()
  assert.equal(await view.getAttribute('data-result-mode'), 'table')
  await page.reload()
  await page.waitForFunction(() => document.querySelector('.workspace-results')?.getAttribute('aria-busy') === 'false')
  assert.equal(await view.getAttribute('data-result-mode'), 'table', 'The chosen view survives reload')
  assert.equal(new URL(page.url()).pathname, '/projects/one/')
  const ready = () => page.waitForFunction(() => document.querySelector('.workspace') && !document.querySelector('.workspace-results[aria-busy="true"]'))
  await selectProject(page, 'two'); await ready()
  assert.equal(new URL(page.url()).pathname, '/projects/two/')
  await selectProject(page, 'one'); await ready()
  await page.goBack(); await ready()
  assert.equal(await page.locator('.project-picker').getAttribute('data-project'), 'two')
  await page.goForward(); await ready()
  assert.equal(await page.locator('.project-picker').getAttribute('data-project'), 'one')
  await page.goto(process.argv[2] + '/projects/one/'); await ready()
  assert.equal(await view.getAttribute('data-result-mode'), 'table', 'A bare project address restores its current tab')
  assert.equal((await page.request.get(process.argv[2] + '/admin/')).status(), 404, 'Removed UI route has no legacy alias')
  const searchTabs = page.locator('.workspace-tabs[data-kind="search"] [role="tab"]')
  const selectedTab = () => page.locator('.workspace-tabs[data-kind="search"] [aria-selected="true"]').getAttribute('data-tab-id')
  const firstTab = await selectedTab(), address = page.url()
  assert.equal(new URL(address).searchParams.has('tab'), false, 'Internal tab IDs stay out of browser addresses')
  await page.getByRole('button', { name:'Add new search tab', exact:true }).click(); await ready()
  const secondTab = await selectedTab()
  assert.notEqual(firstTab, secondTab)
  assert.equal(page.url(), address, 'Different tabs of the same Search Type share a readable address')
  await searchTabs.first().click(); await ready()
  assert.equal(await selectedTab(), firstTab)
  await page.goBack()
  await page.waitForFunction(id => document.querySelector('.workspace-tabs[data-kind="search"] [aria-selected="true"]')?.dataset.tabId === id, secondTab)
  await ready()
  await page.goBack()
  await page.waitForFunction(id => document.querySelector('.workspace-tabs[data-kind="search"] [aria-selected="true"]')?.dataset.tabId === id, firstTab)
  await ready()
  await page.goForward()
  await page.waitForFunction(id => document.querySelector('.workspace-tabs[data-kind="search"] [aria-selected="true"]')?.dataset.tabId === id, secondTab)
  await ready()
  await page.reload(); await ready()
  assert.equal(await selectedTab(), secondTab, 'Reload retains the selected tab without exposing its ID')
  assert.equal(page.url(), address)
  await page.locator('.workspace-tabs[data-kind="search"]').getByRole('button', { name:/^Close search tab:/ }).last().click(); await ready()
  await page.goBack(); await ready()
  assert.equal(await selectedTab(), firstTab, 'History for a closed tab falls back to the retained current tab')
  assert.equal(await searchTabs.count(), 1, 'History does not recreate a closed tab')
  const history = page.locator('.workspace-tab-history')
  await history.locator(':scope > summary').click()
  await history.getByRole('button', { name:'Clear history', exact:true }).click()
  await history.waitFor({ state:'detached' })
  assert.deepEqual(errors, [], 'A menu action may unmount its own menu before the click bubbles')
  const recipient = await browser.newPage({ viewport:{ width:1280, height:900 } })
  await recipient.goto(address)
  await recipient.getByLabel('Login', { exact:true }).fill('admin')
  await recipient.getByLabel('Password', { exact:true }).fill('private-test-password')
  await recipient.getByRole('button', { name:'Sign in', exact:true }).click()
  await recipient.waitForFunction(() => document.querySelector('.workspace-results')?.getAttribute('aria-busy') === 'false')
  assert.equal(recipient.url(), address, 'A copied address opens the Search Type without private tab IDs')
  assert.equal(await recipient.locator('.workspace-tabs[data-kind="search"] [role="tab"]').count(), 1)
  await recipient.close()
  const fresh = await browser.newPage({ viewport:{ width:1280, height:900 } })
  await fresh.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode:'dark', language:'en' })))
  const link = 'skey://contract/entity?code=A'
  await fresh.goto(process.argv[2] + '/projects/one/?' + new URLSearchParams({ link }))
  await fresh.getByLabel('Login', { exact: true }).fill('admin')
  await fresh.getByLabel('Password', { exact:true }).fill('private-test-password')
  await fresh.getByRole('button', { name:'Sign in', exact:true }).click()
  const details = fresh.getByRole('dialog', { name:'Object details', exact:true })
  await details.waitFor()
  assert.equal(await fresh.locator('.project-picker').getAttribute('data-project'), 'one', 'A link without project uses the path before sign-in')
  assert.equal(new URL(fresh.url()).pathname, '/projects/one/')
  await fresh.reload(); await details.waitFor()
  assert.equal(new URL(fresh.url()).searchParams.get('link'), link)
  await fresh.close()
  assert.deepEqual(errors, [])
  console.log('PASS navigation: drawer, touch, Search Type, clean shared URLs, same-address tab Back/Forward/reload, closed-tab history, copied address and fresh skey sign-in')
} catch (error) { await browser.contexts()[0]?.pages()[0]?.screenshot({path:'../.screenshots/navigation-failure.png'}); throw error }
finally { await browser.close() }
