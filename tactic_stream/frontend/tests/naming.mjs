import { selectProject } from './project_selection.mjs'
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, hasTouch: true })
await context.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ language: 'en', theme: 'md3', mode: 'dark' })))
const page = await context.newPage(), errors = []
page.setDefaultTimeout(10000)
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(process.argv[2] + '/projects/admin/?search_type=sthpw/project&view=table')
  await page.getByLabel('Login', { exact: true }).fill('admin')
  await page.getByLabel('Password', { exact: true }).fill('private-test-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).tap()
  await selectProject(page, 'one')
  await page.getByLabel('More options', { exact: true }).tap()
  await page.locator('.settings-menu').getByRole('button', { name: 'Administration', exact: true }).tap()
  const types = page.locator('.search-types-editor')
  await types.locator('[data-metric="total"]').waitFor()
  await types.getByRole('button', { name: 'contract/entity', exact: true }).tap()
  await types.getByRole('tab', { name: 'Naming', exact: true }).tap()
  const editor = page.locator('.naming-editor'), actions = page.getByRole('group', { name: 'Naming actions', exact: true })
  const ready = () => page.waitForFunction(() => document.querySelector('.naming-editor')?.getAttribute('aria-busy') === 'false')
  await ready()
  const originalRules = await editor.locator('.naming-catalog button').count()
  await actions.getByRole('button', { name: 'Create naming rule', exact: true }).tap()
  await editor.getByLabel('Rule context (empty means any)', { exact: true }).fill('publish/*')
  await editor.getByLabel('Directory naming', { exact: true }).fill('{project.code}/{sobject.code}/{snapshot.context}')
  await editor.getByLabel('File naming', { exact: true }).fill('{sobject.code}_v{version}.{ext}')
  await editor.getByLabel('Example file', { exact: true }).fill('example.exr')
  await editor.getByLabel('Preview context', { exact: true }).fill('publish/main')
  await editor.getByLabel('Version', { exact: true }).fill('12')
  await editor.getByRole('button', { name: 'Evaluate naming', exact: true }).tap()
  await ready()
  assert.equal(await editor.getByRole('alert').count(), 0)
  await editor.locator('.naming-path').getByText('one/A/publish/main/A_v012.exr', { exact: true }).waitFor()
  await actions.getByRole('button', { name: 'Save naming rule', exact: true }).tap()
  await ready()
  assert.equal(await editor.getByRole('alert').count(), 0)
  assert.equal(await actions.getByRole('button', { name: 'Save naming rule', exact: true }).isDisabled(), true)
  await editor.getByLabel('File naming', { exact: true }).fill('{sobject.code}_edited_v{version}.{ext}')
  page.once('dialog', dialog => dialog.dismiss())
  await types.getByRole('tab', { name: 'Summary', exact: true }).tap()
  assert.equal(await editor.isVisible(), true)
  assert.equal(await editor.getByLabel('File naming', { exact: true }).inputValue(), '{sobject.code}_edited_v{version}.{ext}')
  await editor.locator('.naming-advanced > summary').tap()
  await editor.getByLabel('Snapshot type', { exact: true }).last().fill('file')
  page.once('dialog', dialog => dialog.accept())
  await actions.getByRole('button', { name: 'Save naming rule', exact: true }).tap()
  await ready()
  await types.locator('.administration-document').evaluate(node => node.scrollTop = 0)
  if (process.argv[3]) await page.screenshot({ path: process.argv[3].replace('-mobile.png', '-desktop.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 320, height: 740 })
  await actions.getByRole('button', { name: 'Duplicate selected rule', exact: true }).tap()
  await editor.getByLabel('Rule context (empty means any)', { exact: true }).fill('duplicate')
  await actions.getByRole('button', { name: 'Save naming rule', exact: true }).tap()
  await ready()
  assert.equal(await editor.getByRole('alert').count(), 0)
  assert.equal(await editor.locator('.naming-catalog button').count(), originalRules + 2)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await editor.getByRole('button', { name: 'Evaluate naming', exact: true }).tap()
  await ready()
  assert.equal(await editor.locator('.naming-results .notice').count(), 1)
  if (process.argv[3]) { await editor.locator('.naming-results').scrollIntoViewIfNeeded(); await page.screenshot({ path: process.argv[3], animations: 'disabled' }) }
  assert.deepEqual(errors, [])
  console.log('naming: native preview, TSQL context, create/save/duplicate, advanced fields, draft guard and touch passed')
} catch (error) { console.error(errors); console.error(await page.locator('.naming-editor').innerText()); await page.screenshot({ path: process.argv[3].replace('.png', '-failure.png') }); throw error } finally { await browser.close() }
