import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { selectProject } from './project_selection.mjs'
const base = process.argv[2]
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: 'dark', hasTouch: true })
  const errors = []; page.on('pageerror', error => errors.push(error.message)); page.setDefaultTimeout(12000)
  await page.addInitScript(() => localStorage.setItem('tactic_stream.appearance', JSON.stringify({ mode: 'dark', language: 'en' })))
  await page.route('http://tactic-stream.test/**', async route => { const url = new URL(route.request().url()); await route.fulfill({ response: await route.fetch({ url: base + url.pathname + url.search, headers: { ...route.request().headers(), origin: base, referer: base + '/' } }) }) })
  await page.goto('http://tactic-stream.test/')
  await page.getByLabel('Login', { exact: true }).fill(process.env.STREAM_CHECK_LOGIN || 'admin')
  await page.getByLabel('Password', { exact: true }).fill(process.env.STREAM_CHECK_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.locator('.project-picker').waitFor()
  await selectProject(page, process.env.STREAM_CHECK_PROJECT)
  const openMenu = async name => { await page.getByLabel('More options', { exact: true }).click(); await page.locator('.settings-menu').getByRole('button', { name, exact: true }).click() }
  async function check(dialog) {
    await dialog.waitFor()
    await dialog.locator('.app-window-controls:visible').waitFor()
    assert.equal(await dialog.locator('.app-window-controls:visible').count(), 1)
    if (await dialog.getByRole('button', { name: 'Restore window', exact: true }).count()) await dialog.getByRole('button', { name: 'Restore window', exact: true }).click()
    const original = await dialog.boundingBox()
    await dialog.getByRole('button', { name: 'Maximize window', exact: true }).click()
    assert.equal((await dialog.boundingBox()).width, 1440); assert.equal((await dialog.boundingBox()).height, 1000)
    await dialog.getByRole('button', { name: 'Restore window', exact: true }).click()
    const restored = await dialog.boundingBox(); assert(Math.abs(original.x - restored.x) < 1); assert(Math.abs(original.width - restored.width) < 1)
    await dialog.locator('.app-window-titlebar').first().focus(); await page.keyboard.press('Alt+ArrowRight')
    const moved = await dialog.boundingBox(); assert(moved.x >= restored.x)
    await page.keyboard.press('Alt+Shift+ArrowRight')
    assert(Math.abs((await dialog.boundingBox()).width - moved.width - 10) < 1)
    await page.keyboard.press('Alt+Shift+ArrowLeft')
    const edge = await dialog.locator(':scope > .app-window-resize.right').boundingBox()
    await page.mouse.move(edge.x + edge.width / 2, edge.y + edge.height / 2)
    await page.mouse.down(); await page.mouse.move(edge.x + 26, edge.y + edge.height / 2)
    assert((await dialog.boundingBox()).width > moved.width)
    await page.keyboard.press('Escape'); await page.mouse.up()
    assert(Math.abs((await dialog.boundingBox()).width - moved.width) < 1, 'Escape cancels the resize without closing the window')
    await page.setViewportSize({ width: 320, height: 760 })
    const mobile = await dialog.boundingBox(); assert(mobile.x >= 0 && mobile.x + mobile.width <= 321); assert.equal(await dialog.locator('.app-window-controls:visible').count(), 0)
    await page.setViewportSize({ width: 1440, height: 1000 })
  }
  await openMenu('Configuration')
  const configuration = page.locator('dialog[aria-labelledby="configuration-title"]')
  await check(configuration); await configuration.screenshot({ path: '../.screenshots/handler-current/stream-window-configuration.png', animations: 'disabled' })
  await configuration.getByRole('button', { name: 'Close', exact: true }).click()
  await openMenu('Script Editor'); const editor = page.locator('.script-editor-dialog'); await check(editor)
  await editor.getByLabel('Close script editor', { exact: true }).click()
  await openMenu('Debug Log'); const debug = page.locator('.debug-log-dialog'); await check(debug)
  await debug.getByLabel('Close Debug Log', { exact: true }).click()
  await openMenu('Debug Log'); await debug.locator('.app-window-controls').waitFor(); assert.equal(await debug.locator('.app-window-controls').count(), 1)
  await debug.getByLabel('Close Debug Log', { exact: true }).click()
  assert.deepEqual(errors, [])
  console.log('PASS common windows: configuration/editor/debug, maximize/restore, keyboard move, mobile, reopen without duplicated controls')
} finally { await browser.close() }
