const source = `# def hidden\n@decorator\ndef example(self):\n    text = """return # string\n<span>"""\n    return print('if #', 0xFF, .5, True)\n`
const tokens = pythonTokens(source)
assert.equal(tokens.map(token => token.text).join(''), source)
assert.equal(tokens.find(token => token.text === 'example').role, 'definition')
assert.equal(tokens.find(token => token.text === 'print').role, 'type')
assert.equal(tokens.find(token => token.text === '0xFF').role, 'number')
assert.equal(tokens.find(token => token.text === '"""return # string\n<span>"""').role, 'string')
assert.equal(tokens.find(token => token.text === "'if #'").role, 'string')
assert.equal(pythonTokens('"incomplete').map(token => token.text).join(''), '"incomplete')

