import { selectProject } from './project_selection.mjs'
import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, hasTouch: true })
const page = await context.newPage()
page.setDefaultTimeout(12000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(process.argv[2] + '/projects/admin/?search_type=sthpw/project&view=table')
  await page.getByLabel('Login', { exact: true }).fill('admin')
  await page.getByLabel('Password', { exact: true }).fill('private-test-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await selectProject(page, 'one')
  await page.getByLabel('More options', { exact: true }).click()
  await page.locator('.settings-menu').getByRole('button', { name: 'Administration', exact: true }).click()
  const editor = page.locator('.search-types-editor')
  const administration = page.getByRole('dialog', { name: 'Administration', exact: true })
  const waitReady = () => page.waitForFunction(() => document.querySelector('.search-types-editor')?.getAttribute('aria-busy') === 'false')
  await waitReady()
  assert.equal(await editor.getByRole('alert').count(), 0)
  await editor.getByRole('button', { name: 'contract/entity_in_collection', exact: true }).tap()
  await waitReady()
  assert.equal(await editor.locator('[data-metric="total"]').textContent(), '8')
  assert.equal(await editor.locator('[data-metric="active"]').textContent(), '7')
  assert.equal(await editor.locator('[data-metric="retired"]').textContent(), '1')
  assert.equal(await editor.locator('.relationship-node').count(), 3)
  assert.equal(await editor.locator('.relationship-edge').count(), 3)
  await editor.getByText('This is a link table for a many-to-many relationship, not a separate object category.', { exact: true }).waitFor()
  await editor.getByRole('button', { name: 'Zoom in', exact: true }).tap()
  assert.equal(await editor.getByLabel('Zoom level', { exact: true }).textContent(), '110%')
  await editor.getByRole('button', { name: 'Zoom out', exact: true }).tap()
  assert.equal(await editor.getByLabel('Zoom level', { exact: true }).textContent(), '100%')
  const map = editor.getByRole('region', { name: 'Relationship map', exact: true })
  await map.evaluate(node => { node.scrollLeft = 120; node.scrollTop = 80 })
  await editor.getByRole('button', { name: 'Reset canvas view', exact: true }).tap()
  assert.deepEqual(await map.evaluate(node => [node.scrollLeft, node.scrollTop]), [0, 0])
  if (process.argv[3]) {
    await editor.locator('.administration-document').evaluate(node => { node.scrollTop = 0 })
    await page.screenshot({ path: process.argv[3].replace('-mobile.png', '-summary.png'), fullPage: true, animations: 'disabled' })
  }
  await page.setViewportSize({ width: 320, height: 740 })
  await map.scrollIntoViewIfNeeded()
  const bounds = await map.boundingBox(), touch = await context.newCDPSession(page)
  const y = bounds.y + bounds.height / 2
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: bounds.x + bounds.width * .8, y }] })
  for (const fraction of [.7, .6, .5, .4, .3, .2]) await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: bounds.x + bounds.width * fraction, y }] })
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await page.waitForFunction(node => node.scrollLeft > 0, await map.elementHandle())
  // Stop the swipe's inertia before resizing and tapping another screen.
  await map.evaluate(node => node.scrollTo({ left: node.scrollLeft, top: node.scrollTop, behavior: 'instant' }))
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  if (process.argv[3]) await page.screenshot({ path: process.argv[3].replace('-mobile.png', '-summary-mobile.png'), fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 1440, height: 900 })
  await administration.getByRole('button', { name: 'New Search Type', exact: true }).click()
  assert.equal(await administration.getByRole('button', { name: 'Save', exact: true }).isDisabled(), true)
  await editor.getByRole('button', { name: 'Next', exact: true }).click()
  await editor.getByRole('alert').getByText('Enter a Search Type title', { exact: true }).waitFor()
  await page.getByLabel('Title', { exact: true }).fill('Browser editor')
  await editor.getByRole('textbox', { name:'Description', exact:true }).fill('Created through the editor')
  await editor.getByRole('button', { name: 'Next', exact: true }).click()
  await editor.getByText('Default fields', { exact: true }).waitFor()
  await page.getByLabel('Field name', { exact: true }).fill('code')
  await editor.getByRole('button', { name: 'Add field', exact: true }).click()
  await editor.getByRole('alert').getByText('A column with this name already exists', { exact: true }).waitFor()
  await page.getByLabel('Field name', { exact: true }).fill('amount')
  await page.getByLabel('Field type', { exact: true }).selectOption('integer')
  await editor.getByRole('button', { name: 'Add field', exact: true }).click()
  assert.equal(await editor.getByText('amount', { exact: true }).count(), 1)
  assert.equal(await editor.getByRole('button', { name: 'Remove draft field amount', exact: true }).count(), 1)
  await editor.getByRole('button', { name: 'Next', exact: true }).click()
  await editor.getByRole('heading', { name: 'Ready to create', exact: true }).waitFor()
  await editor.getByText('amount (integer)', { exact: true }).waitFor()
  await page.setViewportSize({ width: 320, height: 740 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.equal(await editor.locator('.administration-catalog').isVisible(), false)
  if (process.argv[3]) await page.screenshot({ path: process.argv[3].replace('-mobile.png', '-wizard-mobile.png'), fullPage: true, animations: 'disabled' })
  await editor.getByRole('button', { name: 'Back', exact: true }).click()
  await editor.getByRole('button', { name: 'Remove draft field amount', exact: true }).waitFor()
  await editor.getByRole('button', { name: 'Next', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 900 })
  await administration.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('heading', { name: 'one/browser_editor', exact: true }).waitFor()
  await waitReady()
  assert.equal(await editor.getByRole('alert').count(), 0)
  assert.equal(await administration.getByRole('button', { name: 'Save', exact: true }).isDisabled(), true)
  assert.equal(await editor.getByRole('button', { name: 'Remove draft field amount', exact: true }).count(), 0)
  await page.getByLabel('Title', { exact: true }).fill('Unsaved title')
  await administration.locator('.administration-navigation').getByRole('button', { name: 'Groups', exact: true }).click()
  await administration.locator('.administration-navigation').getByRole('button', { name: 'Search Types', exact: true }).click()
  assert.equal(await page.getByLabel('Title', { exact: true }).inputValue(), 'Unsaved title')
  assert.equal(await page.getByLabel('Administration project', { exact: true }).isDisabled(), true)
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByLabel('Title', { exact: true }).press('Escape')
  assert.equal(await administration.evaluate(node => node.matches(':modal')), true)
  await page.getByLabel('Title', { exact: true }).fill('Browser editor')
  await page.setViewportSize({ width: 320, height: 740 })
  assert.equal(await page.getByRole('navigation', { name: 'Administration sections', exact: true }).getByRole('button', { name: 'Groups', exact: true }).isVisible(), false)
  await editor.getByRole('tab', { name: 'Fields', exact: true }).click()
  await page.getByLabel('Field name', { exact: true }).fill('memo')
  await page.getByLabel('Field type', { exact: true }).selectOption('text')
  await editor.getByRole('button', { name: 'Add field', exact: true }).click()
  await administration.getByRole('button', { name: 'Save', exact: true }).click()
  await waitReady()
  assert.equal(await editor.getByRole('alert').count(), 0)
  assert.equal(await editor.getByRole('button', { name: 'Delete field id', exact: true }).isDisabled(), true)
  await editor.getByRole('button', { name: 'Delete field memo', exact: true }).click()
  await editor.getByRole('button', { name: 'Undo deletion of memo', exact: true }).waitFor()
  await editor.getByRole('button', { name: 'Undo deletion of memo', exact: true }).click()
  assert.equal(await administration.getByRole('button', { name: 'Save', exact: true }).isDisabled(), true)
  await editor.getByRole('button', { name: 'Delete field memo', exact: true }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await administration.getByRole('button', { name: 'Save', exact: true }).click()
  await editor.getByRole('button', { name: 'Undo deletion of memo', exact: true }).waitFor()
  page.once('dialog', dialog => dialog.accept())
  await administration.getByRole('button', { name: 'Save', exact: true }).click()
  await waitReady()
  assert.equal(await editor.getByRole('button', { name: 'Delete field memo', exact: true }).count(), 0)
  await editor.getByLabel('Find a field', { exact: true }).fill('amount')
  assert.equal(await editor.getByRole('button', { name: 'Delete field amount', exact: true }).count(), 1)
  assert.equal(await editor.getByRole('button', { name: 'Delete field name', exact: true }).count(), 0)
  await editor.getByLabel('Find a field', { exact: true }).fill('')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.ok(await editor.getByRole('button', { name: 'Add field', exact: true }).evaluate(node => node.getBoundingClientRect().height >= 36))
  if (process.argv[3]) await page.screenshot({ path: process.argv[3], fullPage: true, animations: 'disabled' })
  await page.getByLabel('Administration project', { exact: true }).selectOption('two')
  await waitReady()
  await administration.getByRole('button', { name: 'Close administration', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.table-container')?.getAttribute('aria-busy') === 'false')
  await editor.waitFor({ state: 'detached' })
  assert.equal(await page.getByLabel('Project', { exact: true }).getAttribute('data-project'), 'one')
  assert.deepEqual(errors, [])
  console.log('Search Types: create, fields, save, draft guards and 320px touch passed')
} finally { await browser.close() }
